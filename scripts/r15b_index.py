def block(name, caption):
    parts = ['<div class="shot">', '<div class="cap">%s</div>' % caption]
    if os.path.exists(os.path.join(SHOTS, name)):
        parts.append('<img src="%s" alt="%s">' % (name, name))
    else:
        parts.append('<div class="missing">снимок не найден: %s</div>' % name)
    parts.append('</div>')
    return parts


def main():
    parts = [HEAD, '<h1>Объединённое ревью 15.08.2026 — фазы 7–15</h1>',
             '<div class="lead">Вторая сессия: части работы, карточка '
             'ученика, минуты вместо попыток, своё поле даты и календарь, '
             'конструктор работы, конструктор подборки, экраны «Описать '
             'словами», печать и <code>.tex</code>, сверка группы с '
             'индивидуальным занятием. Ниже — по снимку на каждую заметную '
             'правку, затем те же экраны в тёмной теме и на 380 '
             'пикселях.</div>']
    for name, caption in CAPTIONS:
        parts.extend(block(name, caption))

    for title, suffix, note in (
            ('Тёмная тема', '-тёмная.png',
             'Все новые цвета заведены токенами, поэтому вторая тема '
             'меняется в той же точке, что первая.'),
            ('380 пикселей', '-380.png',
             'Содержимое укладывается в ширину. Саму страницу по-прежнему '
             'тянет шапка <code>_nav.html</code>: это старая поломка, '
             'чинить её запрещено.')):
        names = sorted(n for n in os.listdir(SHOTS)
                       if n.startswith(PREFIX) and n.endswith(suffix))
        if not names:
            continue
        parts.append('<h2>%s</h2>' % title)
        parts.append('<div class="lead">%s</div>' % note)
        for name in names:
            parts.extend(block(
                name, name.replace(PREFIX, '').replace(suffix, '')))

    out = os.path.join(SHOTS, 'index_r15b.html')
    with io.open(out, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(parts))
    print('готово:', out)


if __name__ == '__main__':
    main()
