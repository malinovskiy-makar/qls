def block(name, caption):
    parts = ['<div class="shot">', '<div class="cap">%s</div>' % caption]
    if os.path.exists(os.path.join(SHOTS, name)):
        parts.append('<img src="%s" alt="%s">' % (name, name))
    else:
        parts.append('<div class="missing">снимок не найден: %s</div>' % name)
    parts.append('</div>')
    return parts


def main():
    parts = [HEAD, '<h1>Сессия 10: добор после сессии 9</h1>',
             '<div class="lead">Остаток фазы 10: панель «Настройки работы» '
             'сведена в один партиал на четырёх экранах создания, фильтры '
             'ручного поиска собраны в карточку, поле срока стало своим. '
             'Ниже — панель на всех экранах, затем три пути создания работы '
             'целиком, затем тёмная тема и 380 пикселей.</div>']
    for name, caption in CAPTIONS:
        parts.extend(block(name, caption))

    for title, prefix, note in (
            ('Тёмная тема', THEME_PREFIX,
             'Те же экраны с тёмной темой. Все цвета — через '
             '<code>var(--…)</code>, поэтому панель перекрашивается сама.'),
            ('380 пикселей', NARROW_PREFIX,
             'Панель укладывается в ширину и не тянется вбок. Саму страницу '
             'по-прежнему тянет шапка <code>_nav.html</code> — старая '
             'поломка, чинить её в этой сессии было запрещено.')):
        names = sorted(n for n in os.listdir(SHOTS)
                       if n.startswith(prefix) and n.endswith('.png'))
        if not names:
            continue
        parts.append('<h2>%s</h2>' % title)
        parts.append('<div class="lead">%s</div>' % note)
        for name in names:
            parts.extend(block(name, name.replace(prefix, '').replace('.png', '')))

    out = os.path.join(SHOTS, 'index_session10.html')
    with io.open(out, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(parts))
    print('готово:', out)


if __name__ == '__main__':
    main()
