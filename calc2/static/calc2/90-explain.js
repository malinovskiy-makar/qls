/* Разбор для текущей сцены: сначала то, что написала сама сцена, иначе реестр.
   Ключ берём у карточки (STATE.sceneKey), потому что у подрежимов свои тексты. */
function sceneExplainHtml() {
  const key = STATE.sceneKey;
  if (!key) return '';
  const html = SCENE_EXPLAIN[key];
  if (!html) return '';
  return '<div class="sb-note">' + html + '</div>';
}
