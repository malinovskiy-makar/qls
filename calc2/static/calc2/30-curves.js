function labelCurve(g, f, txt, color, opts) {
  const o = opts || {};
  const anchorKey = o.key || (o.curve && o.curve.id) || txt;
  const a = curveAnchor(f, o.from, o.to, anchorKey);
  if (!a) return null;
  const m = CONFIG.margin;
  const right = W - m.right;
  const wide = txt.length * 6.3 + 8;              // грубая ширина текста, px
  const rawPx = sx(a.q), rawPy = sy(a.v);
  // Переворот с запасом: у самой границы решение не меняется туда-сюда.
  const over = rawPx + wide - right;
  const wantLeft = over > FLIP_HYST ? true : (over < -FLIP_HYST ? false : null);
  const key = o.key || (o.curve && o.curve.id) || txt;
  const prevLeft = (_labelPos.get(key) || {}).toLeft;
  const sm = smoothLabel(key, rawPx, rawPy,
                         wantLeft === null ? (prevLeft === undefined ? over > 0 : prevLeft) : wantLeft);
  const px = sm.px, py = sm.py;
  const toLeft = sm.toLeft;
  /* ⚠️ У ПЕРЕВОРОТА ВВЕРХ-ВНИЗ ТОЖЕ ДОЛЖЕН БЫТЬ ЗАПАС.

     Горизонтальному перевороту запас дали давно (FLIP_HYST), а вертикальный
     решался голым сравнением: подпись стоит над кривой, а если упёрлась в
     верхний край — под кривой. Разница между вариантами 21 px, и пока порог
     проходил туда-сюда, подпись прыгала на эти самые 21 px на каждом шаге
     ползунка. Замер дефекта: 87,6 → 95,8 → 101,1 → 93,1 → 86,3 → 94,5 → 85,8,
     до 13,6 px за шаг при НЕПОДВИЖНОЙ плоскости.

     Теперь сторона помнится вместе с местом. Уходим с неё, только когда она
     стала по-настоящему плохой (подпись вылезает за холст), а возвращаемся —
     когда стало заведомо просторно. На самой границе решение не меняется. */
  const topLimit = m.top + 12, botLimit = H - m.bottom - 4;
  let below = (sm.below === undefined) ? !!o.below : sm.below;
  if (!below && py - 7 < topLimit) below = true;                       // упёрлись в верх
  else if (below && py + 14 > botLimit) below = false;                 // упёрлись в низ
  else if (below && !o.below && py - 7 > topLimit + FLIP_HYST) below = false;
  else if (!below && o.below && py + 14 < botLimit - FLIP_HYST) below = true;
  sm.below = below;
  _labelPos.set(key, sm);
  const y = py + (below ? 14 : -7);
  const tx = toLeft ? px - 6 : px + 6;
  void rawPy;                                     // сырое место нужно было только для сглаживания
  const t = g.append('text')
    .attr('class', 'curve-name')     // реестр обозначений и проверка канона ищут по нему
    .attr('x', tx).attr('y', y)
    .attr('text-anchor', toLeft ? 'end' : 'start')
    .attr('font-size', o.size || curveLabelSize()).attr('font-weight', 600).attr('fill', color)
    .attr('paint-order', 'stroke').attr('stroke', COL.halo).attr('stroke-width', 2.6);
  // А28: название кривой набирается как величина (MC, S + t, Q_d), а не
  // обычным текстом. Решает общий разбор, тот же, что у панели и у файла.
  renderLabelText(t, txt);
  // Название кривой правится двойным щелчком прямо на графике.
  if (o.curve) {
    makeRenamable(t, txt, tx, y, (v) => {
      if (v) o.curve.label = v; else delete o.curve.label;
      renderCurveList();
    }, curveShortName(o.curve));   // одиночный щелчок по имени взводит саму кривую
  }
  return a;
}

/* Толщина линии кривой (решение владельца 25.08). Одно место на весь
   калькулятор: и отрисовка, и полоса попадания, и выгрузка спрашивают здесь.

   В сцене сложения сумма — это ответ задачи, а группы — слагаемые к нему,
   поэтому сумма вдвое толще. Во всех остальных сценах толщина прежняя, и
   ни одна из сорока сцен от этой правки не меняется. */
/* Штрих участка «рынка здесь нет». Вдвое длиннее, чем у пунктира первой
   четверти («5 4» и «6 4»): в одной сцене оба должны быть различимы глазом,
   а не только по толщине. */
const GHOST_DASH = '12 6';

function curveWidth(curve) {
  if (typeof sumSceneOn === 'function' && sumSceneOn() && curve && curve.sumGroup) {
    return (curve.kind === 'sum') ? LW.bold : LW.thin;
  }
  return LW.base;
}

// Рисуем все видимые кривые внутри «окна» первой четверти.
function drawCurves() {
  /* ⚠️ СЛОЙ ПОД КРИВЫЕ, ИДУЩИЕ ПО САМОЙ ОСИ, — ОТДЕЛЬНЫЙ, А НЕ ВЛОЖЕННЫЙ.
     Вложенная обрезка ПЕРЕСЕКАЕТСЯ с родительской, а не заменяет её: группа
     внутри `curves` со своим окном получала бы всё то же тесное окно и
     теряла бы половину толщины по-прежнему (замер 25.08: 1,5 пикселя вместо
     3,2). Поэтому слой лежит рядом, а не внутри. Стоит он ПЕРЕД кривыми:
     подписи и обычные линии должны оставаться сверху. */
  const gLip = svg.append('g').attr('class', 'curves-lip').attr('clip-path', 'url(#plot-clip-lip)');
  const g = svg.append('g').attr('class', 'curves').attr('clip-path', 'url(#plot-clip)');
  const line = d3.line()
    .defined(d => d !== null)               // разрыв там, где формула не считается
    .x(d => sx(d[0])).y(d => sy(d[1]));
  STATE.curves.forEach(curve => {
    /* Пустая строка — это заведённое кнопкой ПОЛЕ, а не кривая: пока формулу
       не набрали, рисовать нечего (решение владельца 22.08). */
    if (!curve.visible || !curve.expr) return;
    const pts = curvePoints(curve);
    const w = curveWidth(curve);
    /* ── УЧАСТОК, КОТОРОГО НЕТ (решение владельца 25.08) ──────────────
       У суммарной кривой бывает кусок, который мы дописали сами, чтобы
       функция не давала NaN: при предложении Q − 100 первый продавец выходит
       на рынок только со ста единиц, и от нуля до ста рыночного предложения
       не существует. Запись там равна нулю, и на холсте это была ровная
       линия по оси Q, неотличимая от самой оси, — читалось как «кривая
       начинается из начала координат».

       Пунктир ТОГО ЖЕ ЦВЕТА И ТОЙ ЖЕ ТОЛЩИНЫ, что сплошной: математически
       кривая здесь есть, а рынка здесь нет, и это столь же важная часть
       картины. Бледнее или тоньше — значило бы «менее важно», а смысл другой.

       ⚠️ НЕ ПУТАТЬ С ПУНКТИРОМ ПЕРВОЙ ЧЕТВЕРТИ. Тот означает продолжение за
       пределы четверти и рисуется тонким и полупрозрачным (1,5 и 0,65 у
       пересечения вне четверти, 0,55·ширины и 0,45 у предельных кривых).
       Этот — полновесный и с ВДВОЕ более длинным штрихом: «12 6» против
       «5 4» и «6 4». Различаются весом, прозрачностью и ритмом штриха. */
    const ghostTo = (typeof sumSceneOn === 'function' && sumSceneOn()) ? (curve.sumGhostTo || 0) : 0;
    if (ghostTo > 1e-9) {
      /* Точку стыка считаем ТОЧНО и кладём в оба куска: узла ровно в ней на
         сетке из 400 отрезков может не оказаться, и между пунктиром и
         сплошной осталась бы щель шириной в шаг сетки. */
      const pJoin = evalCurve(curve, ghostTo);
      const join = isFinite(pJoin) ? [ghostTo, pJoin] : null;
      const ghost = pts.filter(p => p && p[0] < ghostTo - 1e-9);
      const real = pts.filter(p => p && p[0] > ghostTo + 1e-9);
      if (join) { ghost.push(join); real.unshift(join); }
      if (ghost.length > 1) {
        /* Своё окно обрезки: участок «рынка здесь нет» идёт ровно по оси Q,
           и общее окно съедало бы половину его толщины (см. plot-clip-lip). */
        gLip.append('path').datum(ghost)
          .attr('fill', 'none').attr('stroke', curve.color).attr('stroke-width', w)
          .attr('stroke-dasharray', GHOST_DASH)
          .attr('data-curve', curve.id)
          .attr('data-sum-part', 'ghost')
          .attr('d', line);
      }
      g.append('path').datum(real)
        .attr('fill', 'none').attr('stroke', curve.color).attr('stroke-width', w)
        .attr('data-curve', curve.id)
        .attr('data-sum-part', 'real')
        .attr('d', line);
    } else {
      g.append('path').datum(pts)
        .attr('fill', 'none').attr('stroke', curve.color).attr('stroke-width', w)
        .attr('data-curve', curve.id)     // экспорт узнаёт кривую и пишет её формулой
        .attr('d', line);
    }
    /* ⚠️ У ПОЛОСЫ ПОВЕРХ КРИВОЙ ДВА РАЗНЫХ СМЫСЛА, И ОНИ РАЗВЕДЕНЫ.

       Полоса делала сразу две вещи: давала допуск попадания по кривой И
       служила ручкой перетаскивания. Пока они были одним свойством, каждая
       кривая, по которой хочется щёлкнуть, автоматически становилась
       подвижной, а каждая неподвижная — недоступной щелчку. Отсюда обе беды
       ревью сразу: вписанную формулу утягивало мышью, а по кривой, которую
       двигать нельзя, нельзя было и попасть.

       С решением владельца 20.08 («на графике нельзя двигать функции
       графически мышкой») второго свойства не осталось вовсе: полоса строится
       ВСЕГДА и умеет ровно одно — щелчком взвести ключевые точки кривой.
       Курсор поэтому всегда pointer: обещать перетаскивание он не имеет права.

       Ширина 16 px остаётся: владелец просил, чтобы щелчок рядом с кривой
       считался щелчком по кривой.

       Пока набирают вершины или ставят свою точку, полосы нет вовсе: иначе
       она перехватывала бы щелчок, которым ставят точку. */
    if (!canvasArmed()) {
      const hit = g.append('path').datum(pts)
        .attr('fill', 'none').attr('stroke', 'transparent').attr('stroke-width', CURVE_HIT_PX)
        .attr('data-skip-export', '1')    // это полоса для мыши, а не линия графика
        .attr('data-hit', curve.id)
        .attr('data-hit-name', curveShortName(curve))
        .attr('d', line).style('cursor', 'pointer');
      /* Щелчок по полосе взводит кривую: загораются её ключевые точки.
         Порога смещения не вводим — люди щёлкают статично, в один пиксель
         (решение владельца). Перетаскиванию это не мешает: у d3.drag свой
         порог, и после настоящего протягивания щелчок браузером не выдаётся. */
      hit.on('click', (ev) => { ev.stopPropagation(); armCurve(curveShortName(curve)); });
    }
  });
  // Подписи поверх линий (Фаза 1 и 3): имя кривой видно прямо на графике.
  // Отдельным проходом, чтобы текст не оказался под соседней кривой.
  STATE.curves.forEach((curve, i) => {
    if (!curve.visible || !curve.expr) return;   // пустая строка подписи не получает
    /* ⚠️ ДЛИННОЕ ИМЯ ПОКАЗЫВАЕТСЯ ЦЕЛИКОМ. Здесь стоял обрез на четырнадцати
       символах, и «Спрос жителей города» превращался в «Спрос жителей…» даже
       тогда, когда справа оставалось шестьдесят с лишним пикселей свободного
       холста: обрезал жёсткий лимит, а не край поля. Решение владельца: имя
       переезжает целиком левее или правее, на вторую строку не разрывается.
       Переворот у края уже умеет labelCurve — ему и оставляем решение. */
    /* В сцене сложения на холсте стоит ОБОЗНАЧЕНИЕ (D₁, S₂, D, S), а полное
       имя — в левой панели и в подсказке. Иначе шесть подписей по 137–181 px
       выстраиваются вдоль края и читаются одной строкой (Фаза 3). */
    const tag = (typeof sumShortTag === 'function') ? sumShortTag(curve) : null;
    const nm = tag || curveShortName(curve);
    // Соседние кривые в одной точке — разводим по вертикали, иначе подписи слипнутся.
    labelCurve(g, q => evalCurve(curve, q), nm, curve.color, { below: i % 2 === 1, curve });
  });
}

