function sceneDrawsCurveList() {
  if (STATE.mode !== 'market') return true;             // остальные режимы свой список рисуют
  if (STATE.market !== 'monopoly') return true;
  return STATE.monoMode !== 'discr3' && STATE.monoMode !== 'kinked';
}

