# Стартовый запас времени, секунд.
START_SECONDS = 60

# Дельты времени, секунд.
TIME_CORRECT = +6    # верный ответ
TIME_WRONG = -4      # неверный ответ
TIME_SKIP = -2       # пропуск вопроса

# Очки за верный ответ (до множителя).
BASE_POINTS = 100

# Комбо: длина серии верных ответов -> множитель очков.
# Серия 3..5 -> x2, 6..8 -> x3, 9+ -> x4.
COMBO_STEPS = [(9, 4), (6, 3), (3, 2)]

# Прогрессия сложности: первые EASY_PHASE_COUNT вопросов берём из
# сложности 1–2, дальше — выше (с деградацией, если пул мал).
EASY_PHASE_COUNT = 8
EASY_MAX_DIFFICULTY = 2


def combo_multiplier(streak):
    """Множитель очков для текущей серии верных ответов."""
    for threshold, mult in COMBO_STEPS:
        if streak >= threshold:
            return mult
    return 1
