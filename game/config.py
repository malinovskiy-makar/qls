# МЯГКАЯ эскалация: текущее комбо → целевая полоса сложности (включительно).
# Читается сверху вниз, первая подходящая полоса выигрывает.
# ⚠️ Полоса МЯГКАЯ: если под фильтрами игрока в ней пусто, она расширяется,
# а не роняет забег. Пользовательский фильтр сложности — жёсткая рамка,
# эскалация ходит только ВНУТРИ неё.
# ⚠️ Эскалации НЕТ в курированных забегах (набор, вызов дня, дуэль, работа
# над ошибками): там список задан заранее, двигать нечего.
ESCALATION_BANDS = [
    (9, (4, 5)),
    (6, (3, 4)),
    (3, (2, 3)),
    (0, (1, 2)),
]


def escalation_band(streak):
    """Целевая полоса сложности для текущей серии верных ответов."""
    for threshold, band in ESCALATION_BANDS:
        if streak >= threshold:
            return band
    return (DIFFICULTY_MIN, DIFFICULTY_MAX)


