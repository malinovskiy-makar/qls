"""
Общий помощник Блока В: линейные КПВ, пары товаров и две страны.

КПВ задаётся парой максимумов (Mx, My): Y = My·(1 − X/Mx).
Альтернативная стоимость 1 ед. X = My/Mx (в ед. Y).
"""
from fractions import Fraction

from .base import F, fmt_num

# Пары товаров (nom, gen): «производят зерно», «единиц зерна».
PPF_GOODS = [
    (u'зерно', u'зерна'),
    (u'ткань', u'ткани'),
    (u'кофе', u'кофе'),
    (u'сталь', u'стали'),
    (u'мёд', u'мёда'),
    (u'рис', u'риса'),
    (u'хлопок', u'хлопка'),
    (u'сыр', u'сыра'),
]

# Сетка максимумов КПВ: отношения дают красивые альтернативные стоимости.
M_GRID = [20, 30, 40, 50, 60, 80, 100, 120]


def pick_goods_pair(rng):
    """Индексы двух РАЗНЫХ товаров (X, Y)."""
    ix = rng.randrange(len(PPF_GOODS))
    iy = rng.randrange(len(PPF_GOODS) - 1)
    if iy >= ix:
        iy += 1
    return ix, iy


def oc_x(mx, my):
    """Альтернативная стоимость 1 ед. X в ед. Y."""
    return F(my) / F(mx)


def y_on_ppf(mx, my, x0):
    """Максимум Y при производстве x0 единиц X (точка на границе)."""
    return F(my) * (1 - F(x0) / F(mx))
