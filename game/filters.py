u"""Фильтры тренажёра Wecon Rush: словарь групп и разбор параметров.

Раскладка тем БОЛЬШЕ НЕ КОПИЯ: `TOPIC_GROUPS` строится из общего модуля
`problems/sections.py` (04.09.2026, ADR 0071). `FEATURES` и `CHARACTERS`
по-прежнему перенесены из `catalog/filters.py` и ждут своей разметки.

⚠️ ГРУППА ПОКАЗЫВАЕТСЯ, ТОЛЬКО ЕСЛИ У НЕЁ ЕСТЬ ВАРИАНТЫ (`Group.visible`).
«Особенности» и «Характер задачи» в базе не размечены — у них ноль вариантов
и в разметку они не попадают вовсе. Серый переключатель, который не
нажимается, хуже его отсутствия. Это ОБЩЕЕ правило, а не заглушка на два
поля: появится разметка — группы включатся сами.

⚠️ ВАРИАНТ С НУЛЁМ ВНУТРИ ПОКАЗАННОЙ ГРУППЫ — ДРУГОЕ ДЕЛО. Ноль честно
говорит «таких вопросов в пуле пока нет»; молчание неотличимо от «фильтр
сломался».
"""

from problems.sections import canonical_groups

# ── Тема: пять блоков над каноническими темами ───────────────────────────
#
# Копии раскладки больше нет: и каталог, и тренажёр читают один модуль
# `problems/sections.py`. Это закрывает предупреждение в шапке файла — две
# копии одной раскладки действительно разошлись бы при первом добавлении
# темы, и разошлись бы молча. ADR 0071.
TOPIC_GROUPS = [
    [key, label, list(names)] for key, label, names in canonical_groups()
]

# Готовые наборы кнопок «Микро» / «Макро»: ключи блоков общего модуля.
TOPIC_PRESETS = {
    'micro': ['micro'],
    'macro': ['macro'],
}

# ── Особенности и характер задачи — ЗАГОТОВКИ ────────────────────────────
#
# Полей в модели нет ни у одной строки, поэтому `feature_options()` и
# `character_options()` возвращают пустоту, и обе группы скрываются.
# Ключи — те же, что в `catalog/filters.py`: когда разметка появится и
# модули сведут, переименовывать будет нечего.
FEATURES = [
    ('graph', 'Есть график'),
    ('table', 'Есть таблица'),
    ('proof', 'Требует доказательства'),
]

CHARACTERS = [
    ('calc', 'Количественная'),
    ('theory', 'Качественная'),
]


def feature_options(pool_counts=None):
    u"""Варианты группы «Особенности». Пусто — поля в базе нет."""
    return []


def character_options(pool_counts=None):
    u"""Варианты группы «Характер задачи». Пусто — поля в базе нет."""
    return []


def visible_groups(**counts):
    u"""Какие необязательные группы показывать. Пустая группа не рисуется."""
    return {
        'feature': bool(feature_options()),
        'character': bool(character_options()),
    }


def canonical_topics():
    u"""Все темы раскладки одним плоским списком, в порядке разделов."""
    out = []
    for _key, _title, names in TOPIC_GROUPS:
        out.extend(names)
    return out
