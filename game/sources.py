def group_of(source_name):
    """Ключ группы для имени источника. Неизвестное имя → 'other'."""
    return SOURCE_GROUPS.get((source_name or '').strip(), 'other')


def group_title(key):
    return GROUP_TITLES.get(key, GROUP_TITLES['other'])


def layout():
    """Раскладка «группа → отсортированный список источников» — для
    экрана фильтров и для распечатки в отчёт."""
    out = {key: [] for key in GROUP_KEYS}
    for name, key in SOURCE_GROUPS.items():
        out.setdefault(key, []).append(name)
    for key in out:
        out[key].sort()
    return out
