"""Сезонное в разделе «Высшая проба»: то, что меняется раз в год, а не с вёрсткой.

⚠️ ОБНОВЛЯТЬ КАЖДЫЙ СЕЗОН. Даты туров живут ТОЛЬКО здесь: посадочная страница `/vp/`
читает их отсюда, в шаблоне их нет. Не забыть про пункт меню «Тренажёр ВП»
(`config/context_processors.py::_menu`): метка NEW у него гаснет по `NEW_BADGE_UNTIL`.

⚠️ ЧИТАТЬ ЧЕРЕЗ МОДУЛЬ (`from vp import config` → `config.CURRENT_TOUR`), а не
`from vp.config import CURRENT_TOUR`: тесты экранов 1 тура подменяют эти значения на
время теста, а копия, взятая при импорте, подмены не увидит.
"""
from datetime import date

#: Тур, под который сделан раздел: посадочная, экран вариантов, таблица, SEO.
CURRENT_TOUR = 2

#: Туры, варианты которых ВИДНЫ в разделе (посадочная, варианты, таблица, sitemap,
#: интро и старт). Скрытый тур не удалён: его попытки и разборы `/vp/r/<код>/`
#: открываются как раньше. Вернуть 1 тур архивом — добавить сюда 1 (экраны архива —
#: отдельная работа, решение владельца 24.10.2026).
VISIBLE_TOURS = (2,)

#: Даты тура: отдельные дни (`days`) или период «с … по …» (`range`). Пусто — фразы
#: про даты на странице просто нет.
TOUR_DATES = {
    1: ('days', (date(2026, 9, 26), date(2026, 9, 30))),
    2: ('range', (date(2026, 11, 13), date(2026, 11, 22))),
}

#: Классы по турам: (значение `VPVariant.grade_band`, подпись). Порядок — порядок
#: переключателя на экране вариантов и вкладок таблицы.
BANDS_BY_TOUR = {
    1: (('9-10', '9–10 классы'), ('11', '11 класс')),
    2: (('9', '9 класс'), ('10', '10 класс'), ('11', '11 класс')),
}

# Метка NEW у пункта шапки видна, пока localdate() < этой даты: до начала 2 тура.
# ⚠️ ДАТА ОТДЕЛЬНАЯ ОТ САМОГО ПУНКТА И ЭТО НАМЕРЕННО: пункт остаётся в шапке и после
# тура, а метка «новое» уходит (решение владельца 22.09.2026).
NEW_BADGE_UNTIL = date(2026, 11, 13)


#: Приглашение на закрытую консультацию перед туром (карточка «Что дальше» на результате).
#: Пусто — карточки нет: появится вместе с приглашениями друзей (отдельная сессия).
VP_INVITE_URL = ''


def bands(tour=None):
    """Классы тура (по умолчанию текущего): `((код, подпись), …)`."""
    return BANDS_BY_TOUR.get(CURRENT_TOUR if tour is None else tour, ())


def all_band_labels():
    """Подписи классов всех туров: `{'9-10': '9–10 классы', '9': '9 класс', …}`."""
    labels = {}
    for pairs in BANDS_BY_TOUR.values():
        labels.update(pairs)
    return labels
