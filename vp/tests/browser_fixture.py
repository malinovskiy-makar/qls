"""Данные для браузерных проверок: настоящий синтетический вариант через загрузчик.

Берём `data/vp/_selftest.yaml` (его структура — та же, что у настоящих вариантов) и
подставляем в первые задания тексты из макетов: длинные условия, суффикс
«денег», пропуск «______», длинные варианты. Так экраны проверяются на живых
строках, а не на «Учебный термин 1». Пишет только в тестовую базу.
"""
import copy
from pathlib import Path

import yaml
from django.conf import settings

from vp import loader

SELFTEST = Path(settings.BASE_DIR) / 'data' / 'vp' / '_selftest.yaml'

LONG_STATEMENTS = {
    1: ('Разница между выручкой фирмы и суммой явных и неявных затрат. Нулевое значение '
        'означает, что владелец получает ровно столько, сколько принесла бы лучшая альтернатива'),
    2: ('Соглашение нескольких продавцов о единой цене или о разделе рынка, позволяющее им '
        'действовать как единый монополист'),
    4: ('Коэффициент, показывающий, во сколько раз может вырасти сумма депозитов при поступлении '
        'в кредитную систему дополнительной единицы резервов'),
    6: ('Число раз, которое денежная единица за год переходит из рук в руки при покупке '
        'конечных товаров и услуг'),
}
GAP_STATEMENT = ('В 1913 г. на заводе Форда сборку автомобиля расщепили на сотни простых '
                 'повторяющихся операций — довели до предела ______, о котором писал ещё '
                 'Адам Смит на примере булавочной мануфактуры.')
GAP_OPTIONS = ['разделение труда', 'урбанизацию', 'бартер', 'автаркию', 'приватизацию']
MULTI_STATEMENT = ('Пекарня арендует помещение за 50 тыс. руб. в месяц, платит пекарям сдельно '
                   'за каждую выпеченную партию и закупает муку. Выберите все верные утверждения.')
MULTI_OPTIONS = [
    'Сдельная оплата труда пекарей относится к постоянным издержкам.',
    'Расходы на муку относятся к переменным издержкам.',
    'При росте выпуска средние постоянные издержки растут.',
    'Арендная плата относится к постоянным издержкам.',
    'Если пекарня ничего не производит, её переменные издержки равны нулю.',
]


def rich_data(slug='vp-ui', duration=1800, title='Пробный вариант 1 тура «Высшей пробы»'):
    """Словарь варианта (как из YAML) с живыми текстами. Сумма баллов остаётся 100."""
    data = yaml.safe_load(SELFTEST.read_text(encoding='utf-8'))
    data = copy.deepcopy(data)
    data.update(slug=slug, title=title, duration_seconds=duration,
                author='Олмат «Экономика»', source_note='')
    for item in data['items']:
        number = item['n']
        if number in LONG_STATEMENTS:
            item['statement'] = LONG_STATEMENTS[number]
        if number == 6:
            item['suffix'] = 'денег'
        if number == 31:
            item['statement'] = GAP_STATEMENT
            item['options'] = GAP_OPTIONS
        if number == 37:
            item['statement'] = MULTI_STATEMENT
            item['options'] = MULTI_OPTIONS
            item['correct'] = [2, 4, 5]
        if number == 43:
            item['statement'] = ('Предприниматель закупает в Китае один вид товара для перепродажи '
                                 'в России. У него есть 330 000 руб., курс — 11 руб. за юань. '
                                 'Чему равна максимальная прибыль в рублях?')
            item['options'] = ['390 000', '400 000', '437 000', '470 000', 'Нет верного ответа']
    return data


def write(data, publish=True):
    """Разобрать и записать через `loader` (как это делает `manage.py import_vp`)."""
    parsed = loader.normalize(data)
    assert not parsed.errors, parsed.errors
    loader.write_variant(parsed, publish=publish)
    return parsed
