# Порядок модели в таблице: место её первого тега, а у моделей только из
# запасного пути место после всех тегов.
_TABLE_ORDER = {}
for _model in list(TAG_TO_MODEL.values()) + list(TOPIC_TO_MODEL.values()):
    _TABLE_ORDER.setdefault(_model, len(_TABLE_ORDER))


def _level(model_key):
    if model_key in BASE:
        return 2
    if model_key in GENERAL:
        return 1
    return 0


def models_for(tag_names, topic_names):
    """Ключи моделей Графиков для задачи, не больше двух, лучшая первой.

    `tag_names` это названия КАНОНИЧЕСКИХ тегов задачи, `topic_names` это
    названия её КАНОНИЧЕСКИХ тем. Тема в счёт только у задачи без единого
    канонического тега. Порядок: частные модели, общие, базовые; внутри
    уровня больше тегов, указавших на модель, выше; дальше порядок таблицы.
    """
    tag_names = [name for name in tag_names if name]
    votes = {}
    if tag_names:
        for name in tag_names:
            model = TAG_TO_MODEL.get(name)
            if model:
                votes[model] = votes.get(model, 0) + 1
    else:
        for name in topic_names:
            model = TOPIC_TO_MODEL.get(name)
            if model:
                votes[model] = votes.get(model, 0) + 1
    ranked = sorted(votes, key=lambda m: (_level(m), -votes[m], _TABLE_ORDER[m]))
    return ranked[:MAX_MODELS]


def calc2_url(model_key, problem_id):
    """Адрес Графиков с моделью и задачей, откуда пришли: `/calc2/?m=…&from=…`."""
    return '%s?%s' % (reverse('calc2:calculator'), urlencode({'m': model_key, 'from': problem_id}))


def coverage(problem_ids, tags_by_problem, topics_by_problem):
    """Сводка покрытия для `manage.py calc2_link_coverage` (только счёт).

    `tags_by_problem` и `topics_by_problem`: id задачи -> названия её
    КАНОНИЧЕСКИХ тегов и тем. Возвращает словарь чисел и распределений.
    """
    from collections import Counter
    out = {'visible': 0, 'with_tag': 0, 'mapped_tag': 0, 'by_topic': 0,
           'with_button': 0, 'two_models': 0, 'tagged_no_button': 0,
           'shown': Counter(), 'first': Counter()}
    for pid in problem_ids:
        tags = tags_by_problem.get(pid, [])
        keys = models_for(tags, topics_by_problem.get(pid, []))
        out['visible'] += 1
        out['with_tag'] += bool(tags)
        out['mapped_tag'] += any(name in TAG_TO_MODEL for name in tags)
        out['by_topic'] += bool(keys) and not tags
        out['tagged_no_button'] += bool(tags) and not keys
        if keys:
            out['with_button'] += 1
            out['first'][keys[0]] += 1
            out['shown'].update(keys)
        out['two_models'] += len(keys) == 2
    return out


def links_for(problem_id, tags, topics):
    """Кнопки для страницы задачи из УЖЕ загруженных тегов и тем (без запросов).

    Берутся только теги `kind='canonical'` и темы `is_canonical=True`.
    """
    keys = models_for([t.name for t in tags if t.kind == 'canonical'],
                      [t.name for t in topics if t.is_canonical])
    return [{'key': key, 'name': MODEL_NAMES[key], 'url': calc2_url(key, problem_id)}
            for key in keys]
