_RX_SPACE = re.compile(r'\s+')
_RX_DASH = re.compile(r'[‐‑‒–—―-]')


def normalize(name):
    """Ключ сравнения названий: регистр, «ё/е», тире и пробелы не важны."""
    text = (name or '').casefold().replace('ё', 'е')
    text = _RX_DASH.sub('-', text)
    return _RX_SPACE.sub(' ', text).strip()


