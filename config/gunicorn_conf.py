# -*- coding: utf-8 -*-
"""Настройки gunicorn контейнера web — подключаются в deploy/entrypoint.sh (`-c`).

Флаги командной строки в entrypoint (воркеры, таймауты, --max-requests) остаются
там, где были: здесь только хуки, которые флагом не задать.
"""


def post_worker_init(worker):
    """Запустить прогрев воркера (catalog/warmup.py) в фоновом потоке и вернуться.

    ⚠️ ПОТОК, А НЕ ПРЯМОЙ ВЫЗОВ (решение владельца 15.09.2026). Арбитр gunicorn
    убивает воркер, молчащий дольше `--timeout` (60 с), в том числе внутри
    этого хука. Сборка корпуса на 14 082 задачах локально шла 22–26 с; сколько
    она займёт на боевом сервере под нагрузкой, заранее не знает никто, и
    воркер, убитый посреди сборки, перезапускался бы и снова погибал. В потоке
    воркер сразу принимает запросы, а поиск, пришедший до конца сборки, ждёт
    её под замком `catalog.rerank.get_corpus()` вместо того, чтобы начать
    вторую.
    ⚠️ daemon=True: остановка воркера не ждёт недостроенный корпус.
    ⚠️ При старте контейнера греются ВСЕ воркеры сразу: первые полминуты после
    выкатки поиск медленнее, остальные страницы отвечают как обычно.
    """
    import threading

    from catalog.warmup import warm_worker

    threading.Thread(target=warm_worker, kwargs={'log': worker.log.info},
                     daemon=True, name='smart-search-warmup').start()
