"""
Настройки для прогона тестов против настоящей PostgreSQL.

Зачем. Локально проект живёт на SQLite, а на проде — PostgreSQL. Это две
разные СУБД с разными правилами, и SQLite прощает то, за что PostgreSQL
выдаёт ошибку: `DISTINCT` вместе с сортировкой по полю не из выборки,
сравнение числа со строкой, порядок русских строк. Тест, зелёный на SQLite,
доказывает математику — но не то, что это заработает на сервере.

Как пользоваться:

    docker compose -f docker-compose.dev.yml up -d
    venv313\\Scripts\\python.exe manage.py test --settings=config.settings_test_pg

Адрес базы берётся из окружения `DATABASE_URL`; если переменной нет —
подставляется адрес контейнера из `docker-compose.dev.yml`. Значение по
умолчанию прописано намеренно: команда, требующая сначала выставить
переменную, на практике не запускается вовсе.

⚠️ ЭТО НЕ ПРОД. Здесь `DEBUG=False`, но никаких боевых предохранителей нет —
файл существует ради тестов. Настройки сервера — `config/settings_production.py`.
"""
import os

from .settings import *  # noqa: F401,F403

# Порт нестандартный (55432) — см. комментарий в docker-compose.dev.yml.
DEFAULT_DATABASE_URL = 'postgres://qls:qls_dev_password@127.0.0.1:55432/qls_dev'

DATABASE_URL = os.environ.get('DATABASE_URL') or DEFAULT_DATABASE_URL

import dj_database_url  # noqa: E402  (после чтения окружения — так читается)

DATABASES = {
    'default': dj_database_url.parse(DATABASE_URL),
}

# Имя тестовой базы задано явно, а не собирается из имени рабочей. Django по
# умолчанию берёт `test_` + имя рабочей базы, и это работает; но когда прогон
# упал на чужой машине или в CI, первый вопрос — «в какой базе это было», и
# ответ на него должен быть в настройках, а не в голове.
DATABASES['default']['TEST'] = {
    'NAME': os.environ.get('TEST_DATABASE_NAME', 'test_qls'),
}

