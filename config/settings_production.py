# ─── Безопасность ────────────────────────────────────────────────────────────

DEBUG = False

# Предохранитель: прод не имеет права подняться в отладочном режиме.
# При DEBUG=True Django показывает трассировки с кусками кода и значениями
# переменных прямо в браузере, а ALLOWED_HOSTS перестаёт работать.
# Падение при старте лучше, чем утечка внутренностей наружу.
if os.environ.get('DJANGO_DEBUG', '').lower() in ('1', 'true', 'yes', 'on'):
    raise RuntimeError(
        'DJANGO_DEBUG выставлен, а на проде отладочный режим запрещён. '
        'Уберите переменную окружения DJANGO_DEBUG.'
    )

# Именно [ ], а не .get(): без ключа сервис обязан упасть при старте,
# а не подняться с тихим значением по умолчанию.
SECRET_KEY = os.environ['SECRET_KEY']

# ─── Кто нам представляется ──────────────────────────────────────────────────

# ⚠️ НИКАКИХ «*». Звёздочка в ALLOWED_HOSTS отключает проверку заголовка Host
# целиком, а на ней держатся ссылки в письмах восстановления пароля и защита
# от отравления кэша: подделанный Host уезжает в письмо как адрес сайта.
ALLOWED_HOSTS = [h.strip() for h in
                 os.environ.get('ALLOWED_HOSTS', '').split(',') if h.strip()]

# Третий предохранитель к тем двум, что уже стоят выше. Пустой ALLOWED_HOSTS
# при DEBUG=False Django не считает ошибкой — он просто отвечает 400 на КАЖДЫЙ
# запрос. Снаружи это неотличимо от «сайт сломался», и разбираться придётся по
# логам прокси. Падение при старте с внятным текстом честнее.
if not ALLOWED_HOSTS:
    raise RuntimeError(
        'ALLOWED_HOSTS пуст. Задайте переменную окружения ALLOWED_HOSTS '
        'через запятую, например: '
        'ALLOWED_HOSTS="weconomics.ru,www.weconomics.ru". '
        'Звёздочка запрещена.'
    )

# Домены, которым доверяем POST-формы. Пусто — значит только свой домен,
# и это правильное значение по умолчанию: список нужен, лишь когда фронт
# и бэкенд живут на разных адресах.
CSRF_TRUSTED_ORIGINS = [o.strip() for o in
                        os.environ.get('CSRF_TRUSTED_ORIGINS', '').split(',')
                        if o.strip()]

# ─── HTTPS ───────────────────────────────────────────────────────────────────

# Прокси завершает SSL и сообщает исходную схему этим заголовком. Без него
# Django считает по-настоящему защищённый запрос обычным.
SECURE_PROXY_SSL_HEADER = ('HTTP_X_FORWARDED_PROTO', 'https')

# ⚠️ ПОЧЕМУ ЭТО МОЖЕТ СЛОМАТЬ ПРОВЕРКУ ЖИВОСТИ. Опасение законное: редирект на
# HTTPS может отвечать 301 там, где проверяющий ждёт 200. На Render это не
# мешало: живость определялась СКАНОМ ПОРТА (TCP), а не HTTP-запросом.
# Обычный трафик приходил через прокси с X-Forwarded-Proto: https, Django
# видел его защищённым и не перенаправлял.
#
# ⚠️ НА НОВОМ ХОСТИНГЕ ПРОВЕРИТЬ ОБЯЗАТЕЛЬНО, ДО ВЫКЛЮЧЕНИЯ ПРЕДОХРАНИТЕЛЯ:
# если живость проверяется HTTP-запросом (не сканом порта), редирект даст
# ей 301 вместо 200, и деплой будет падать. В этом случае — не выключать
# SECURE_SSL_REDIRECT целиком, а добавить адрес проверки в
# SECURE_REDIRECT_EXEMPT. Чек-лист переезда: docs/MIGRATION-CHECKLIST.md.
SECURE_SSL_REDIRECT = True

# ⚠️ ПРОВЕРКА ЖИВОСТИ ВЫВЕДЕНА ИЗ-ПОД РЕДИРЕКТА, И БЕЗ ЭТОГО ОНА НЕ РАБОТАЕТ.
# Ровно тот случай, который предсказан в комментарии выше. Healthcheck
# контейнера стучится к gunicorn НАПРЯМУЮ, по внутренней сети Docker и по
# обычному http — заголовка X-Forwarded-Proto там нет, потому что нет и
# nginx. Django считает такой запрос незащищённым и отвечает 301 на https.
# Замерено локальным запуском 2026-08-21: healthcheck получал 301 и падал,
# контейнер становился unhealthy на полностью живом приложении, а nginx
# с `depends_on` за ним не поднимался вовсе.
#
# Список — регулярные выражения БЕЗ ведущего слэша (так требует Django).
# Наружу /healthz/ не выставлен: nginx его не проксирует.
SECURE_REDIRECT_EXEMPT = [r'^healthz/$']

# ⚠️ HSTS ОТЛОЖЕН ОСОЗНАННО, И ЭТО НЕ ЗАБЫВЧИВОСТЬ. HSTS велит браузеру
# ходить на домен ТОЛЬКО по HTTPS и запоминает это на весь срок. Ошибка тут
# необратима со стороны сервера: пока у посетителя не истечёт запомненный
# срок, вернуть его на HTTP нельзя ничем — ни правкой настроек, ни откатом.
# А includeSubDomains накрывает поддомены, которых у нас ещё нет.
#
# Включаем ПОСЛЕ переезда, когда домен куплен и все поддомены известны и
# умеют HTTPS. Порядок: 300 → сутки → год, каждый шаг с проверкой.
SECURE_HSTS_SECONDS = 0

# ─── Куки ────────────────────────────────────────────────────────────────────

SESSION_COOKIE_SECURE = True
CSRF_COOKIE_SECURE = True
# Кука сессии недоступна из JavaScript: украденный XSS-ом скрипт не сможет
# просто прочитать и отправить её наружу.
SESSION_COOKIE_HTTPONLY = True
# Lax, а не Strict: при Strict переход по ссылке из письма или мессенджера
# приходит без куки, и человек видит себя вышедшим из системы. Для сайта с
# ссылками на подборки и результаты забегов это ежедневная поломка.
SESSION_COOKIE_SAMESITE = 'Lax'
CSRF_COOKIE_SAMESITE = 'Lax'

# ─── Заголовки ответа ────────────────────────────────────────────────────────

# Браузер не додумывает тип содержимого: загруженный файл, который «похож»
# на HTML, не будет выполнен как HTML.
SECURE_CONTENT_TYPE_NOSNIFF = True
# Чужой сайт не узнает из заголовка Referer, с какой именно нашей страницы
# ушёл человек — только то, что с нашего домена.
SECURE_REFERRER_POLICY = 'same-origin'
# Сайт нельзя положить в чужой iframe — это снимает подмену нажатий
# (кликджекинг) на экранах кабинета.
X_FRAME_OPTIONS = 'DENY'

# ─── Redis: обязателен, и это не пожелание ───────────────────────────────────
#
# Четвёртый предохранитель к трём, что стоят выше, и по той же логике: без
# REDIS_URL проект НЕ ломается — он тихо деградирует. `config/settings.py`
# подставит LocMemCache, сайт поднимется, страницы откроются, и никто ничего
# не заметит. А на девяти воркерах это означает девять независимых кэшей:
# попадание примерно один раз из девяти, счётчик неудачных входов у каждого
# воркера свой (попыток до запрета в девять раз больше), сброс кэша доходит
# до одного воркера из девяти. Тихая деградация хуже падения: падение
# чинят в тот же час, а деградацию ищут неделями по жалобам.
#
# Раскладка баз Redis и причина, по которой сессии живут в ОТДЕЛЬНОЙ базе,
# — в config/settings.py у словаря CACHES и в
# docs/adr/0011-redis-cache-and-sessions.md.
if not os.environ.get('REDIS_URL', '').strip():
    raise ImproperlyConfigured(
        'REDIS_URL обязателен в боевых настройках: без него кэш становится '
        'локальным для каждого воркера — это мина №2. Формат: '
        'redis://:пароль@redis:6379 (номер базы дописывается настройками, '
        'указывать его здесь не нужно).'
    )

