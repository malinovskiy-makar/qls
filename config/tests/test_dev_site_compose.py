# -*- coding: utf-8 -*-
"""Описание площадки dev: границы, которые нельзя размыть незаметной правкой.

`manage.py test` docker не поднимает, поэтому свойства площадки проверяются
как свойства ТЕКСТА конфига — так же, как изоляция сервиса поиска в
`catalog/tests/test_search_service.py::ComposeIsolationTests`.

Сторожим ровно то, что стоит дорого при поломке:

1. **Ни одного опубликованного порта.** Публикация портов в Docker обходит
   ufw: правило в ufw есть, а порт открыт всему интернету (docs/SERVER.md).
   Площадка закрыта паролем на уровне nginx — опубликованный порт `web-dev`
   обошёл бы и пароль, и HTTPS разом, и сырой код с main оказался бы
   публично доступен без единого признака этого снаружи.
2. **Никакого второго `search`.** Модель весит 2,12 ГБ, вторая копия не
   помещается в 8 ГБ сервера — запрет P0.
3. **Имя проекта и имя образа отличаются от боевых.** Совпади имя образа —
   сборка площадки перезаписала бы боевой образ, и следующий рестарт боевого
   контейнера поднял бы на бою неподтверждённый код. Совпади имя проекта —
   `up -d` одного гасил бы контейнеры другого.
4. **Сеть внешняя.** Своя сеть означала бы, что боевой nginx не видит
   `web-dev` по имени, а площадке нужен свой порт 443 — а он один.
5. **У каждой службы есть предел памяти.** Площадка живёт на том же сервере
   с 8 ГБ, что и бой. Без предела утечка на площадке съела бы память, и
   OOM-killer ядра выбрал бы жертву сам — а выбирает он самый прожорливый
   процесс, то есть боевой `search` (2,12 ГБ) или боевой `web`. Баг на
   площадке ронял бы настоящий сайт.
"""
import re
from pathlib import Path

from django.test import SimpleTestCase

КОРЕНЬ = Path(__file__).resolve().parents[2]
ПЛОЩАДКА = КОРЕНЬ / 'deploy' / 'docker-compose.dev-site.yml'
БОЙ = КОРЕНЬ / 'deploy' / 'docker-compose.yml'


def _действующие(путь):
    """Строки файла без комментариев: запреты касаются кода, не пояснений."""
    return [с for с in путь.read_text(encoding='utf-8').splitlines()
            if not с.strip().startswith('#')]


class DevSiteComposeTests(SimpleTestCase):

    def test_файл_на_месте(self):
        self.assertTrue(ПЛОЩАДКА.exists(), 'нет %s' % ПЛОЩАДКА)

    def test_ни_одного_опубликованного_порта(self):
        for строка in _действующие(ПЛОЩАДКА):
            self.assertNotRegex(
                строка, r'^\s+ports\s*:',
                'В описании площадки появилась секция ports. Публикация порта '
                'в Docker обходит ufw и открыла бы площадку интернету мимо '
                'пароля nginx. Наружу ходит только боевой nginx.')

    def test_второго_сервиса_поиска_нет(self):
        for строка in _действующие(ПЛОЩАДКА):
            self.assertNotRegex(
                строка, r'^\s\ssearch\s*:',
                'У площадки появился свой сервис search. Модель весит 2,12 ГБ, '
                'вторая копия не поместится в 8 ГБ сервера (запрет P0). '
                'Площадка ходит в боевой `search` по общей сети.')

    def test_имя_проекта_отличается_от_боевого(self):
        имя_площадки = self._имя_проекта(ПЛОЩАДКА)
        имя_боя = self._имя_проекта(БОЙ)
        self.assertTrue(имя_площадки, 'у площадки не задан ключ name')
        self.assertNotEqual(
            имя_площадки, имя_боя,
            'имя compose-проекта площадки совпало с боевым: «up -d» одного '
            'гасил бы контейнеры другого, а тома были бы общими.')

    def test_имя_образа_отличается_от_боевого(self):
        текст = ПЛОЩАДКА.read_text(encoding='utf-8')
        self.assertIn('image: weconomics-web-dev:latest', текст)
        self.assertNotIn('image: weconomics-web:latest', текст,
                         'площадка собирает образ под боевым именем — сборка '
                         'перезаписала бы боевой образ, и рестарт боевого '
                         'контейнера поднял бы неподтверждённый код с main.')

    def test_сеть_внешняя_и_боевая(self):
        текст = ПЛОЩАДКА.read_text(encoding='utf-8')
        self.assertRegex(текст, r'external:\s*true')
        self.assertRegex(текст, r'name:\s*weconomics_backend')

    def test_env_file_свой_а_не_боевой(self):
        текст = '\n'.join(_действующие(ПЛОЩАДКА))
        self.assertIn('/srv/weconomics/dev/.env', текст)
        self.assertNotRegex(
            текст, r'-\s*/srv/weconomics/\.env',
            'площадка читает БОЕВОЙ .env: она подключилась бы к боевой базе, '
            'и dev_scrub стёр бы живых людей.')

    @staticmethod
    def _имя_проекта(путь):
        совпадение = re.search(r'^name:\s*(\S+)\s*$',
                               путь.read_text(encoding='utf-8'), re.MULTILINE)
        return совпадение.group(1) if совпадение else ''

    # Служба → предел памяти, о котором договорились. Числа здесь, а не
    # «лишь бы что-то стояло»: предел в 8 ГБ должен оставлять бою его 6,5.
    ПРЕДЕЛЫ = {'web-dev': 'mem_limit: 900m',
               'ws-dev': 'mem_limit: 300m',
               'redis-dev': 'mem_limit: 128m'}

    def test_у_каждой_службы_есть_предел_памяти(self):
        текст = ПЛОЩАДКА.read_text(encoding='utf-8')
        for служба, предел in self.ПРЕДЕЛЫ.items():
            with self.subTest(служба=служба):
                self.assertIn(
                    предел, текст,
                    'у службы %s нет предела памяти (%s). Без него утечка на '
                    'площадке отдаёт выбор жертвы OOM-killer-у ядра, а тот '
                    'убивает самый крупный процесс — боевой search или web.'
                    % (служба, предел))

    def test_внутренний_предел_redis_ниже_внешнего(self):
        """96 МБ данных против 128 МБ процесса — вытеснение раньше убийства.

        Совпади они, Redis площадки падал бы от OOM вместо того, чтобы
        вытеснить старые ключи по allkeys-lru и продолжить работать.
        """
        текст = ПЛОЩАДКА.read_text(encoding='utf-8')
        self.assertIn('--maxmemory 96mb', текст)
        self.assertIn('mem_limit: 128m', текст)

    def test_все_службы_поднимаются_сами_после_перезагрузки(self):
        текст = chr(10).join(_действующие(ПЛОЩАДКА))
        self.assertEqual(
            текст.count('restart: unless-stopped'), 3,
            'не у всех трёх служб площадки стоит restart: unless-stopped — '
            'после перезагрузки сервера площадка не поднимется сама.')
