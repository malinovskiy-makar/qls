# -*- coding: utf-8 -*-
"""Вычистить людей с площадки `dev.weconomics.ai`, не тронув банк задач.

База площадки — копия БОЕВОЙ базы. Задачи и олимпиады нужны как есть (в этом
смысл площадки: код проверяется на настоящих данных), а вот аккаунты, работы
учеников и всё остальное личное копировать нельзя: площадка закрыта общим
паролем на всю команду, и персональные данные там жить не должны (152-ФЗ).

Порядок применения — `deploy/dev_refresh.sh`: дамп → пересоздать базу →
`pg_restore` → `migrate` → **эта команда** → `fix_sequences --apply`.

⚠️ ДВА ПРЕДОХРАНИТЕЛЯ, И ОБА ОБЯЗАТЕЛЬНЫ.

1. `SITE_ENV` должен быть `dev`. Команда удаляет ВСЕХ пользователей; в
   боевом контейнере `SITE_ENV` равно `prod`, и здесь она обязана
   отказаться до единого удаления. Это единственное, что отличает
   «обновили площадку» от «стёрли боевую базу»: контейнеры одинаковые,
   образ один, команда одна, отличается только окружение.
2. `--yes`. Без него печатается план: сколько чего будет удалено. Случайный
   запуск без флага обязан ничего не делать, а не всё сделать (правило
   `problems/management/commands/CLAUDE.md`).

⚠️ ПОЧЕМУ ЕСТЬ ЯВНЫЙ СПИСОК МОДЕЛЕЙ, А НЕ ТОЛЬКО УДАЛЕНИЕ ПОЛЬЗОВАТЕЛЕЙ.
У части личных сущностей ссылка на автора стоит с `SET_NULL`: `Assignment`,
`Lesson`, `Collection`, `Feedback`, `ExportRecord`. Удали мы только людей —
эти записи ОСТАЛИСЬ БЫ на площадке, просто потеряв владельца: чужие домашние
задания, занятия и жалобы без единого признака, чьи они. Каскад тут не
помощник, а ровно наоборот.

⚠️ ПОЧЕМУ БАНК ПЕРЕЖИВАЕТ УДАЛЕНИЕ ЛЮДЕЙ. У `Problem.owner` стоит
`SET_NULL` — задача теряет владельца, но остаётся. То же у `Collection`…
нет, эту мы сносим сами (см. выше). Полагаться на «я посмотрел модели»
нельзя: одна правка `on_delete` на `CASCADE` — и команда унесёт корпус.
Поэтому число задач и олимпиад сверяется ДО и ПОСЛЕ внутри одной транзакции,
и при расхождении всё откатывается.
"""
from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction

from problems.models import (
    Assignment, Collection, ExportRecord, Lesson, Problem, StudentGroup, User,
)
from problems.models_gamification import ParentLink
from problems.models_platform import Feedback, UserProfile

# ── Четыре тестовых аккаунта площадки ───────────────────────────────────────
#
# ⚠️ ПЯТОЙ РОЛИ — ГОСТЯ — АККАУНТА НЕ НУЖНО И БЫТЬ НЕ ДОЛЖНО. Гость на сайте
# это в точности разлогиненный браузер: каталог, задача, тренажёр открыты без
# входа. Проверяется окном инкогнито, а не логином «dev-guest» — такой логин
# был бы уже вошедшим пользователем с пустыми правами, то есть проверял бы не
# то, что нужно.
#
# ⚠️ РОЛИ ЗАДАЮТСЯ ЧЕРЕЗ UserProfile, А НЕ ЧЕРЕЗ User.role, И ЭТО НЕ ВКУСОВЩИНА.
# Ровно так делает настоящая регистрация (problems/views_auth.py::form_valid):
# создаётся User, затем UserProfile с выбранной ролью, а старое поле
# `User.role` подтягивает сам `UserProfile.sync_user_role()` по таблице
# PROFILE_ROLE_TO_USER_ROLE (tutor→teacher, student→student, parent→viewer).
# Проставь мы `User.role` руками — получили бы ВТОРОЙ способ заводить роли,
# который однажды разойдётся с первым.
#
# Роль профиля → роль пользователя, и что на этом аккаунте смотреть:
#   dev-student  student → student   кабинет ученика, каталог, домашки
#   dev-teacher  tutor   → teacher   панель преподавателя, группы, работы
#   dev-parent   parent  → viewer    экран «Мои дети»
#   dev-admin    tutor   → (не трогается, см. ниже)  /admin/
АККАУНТЫ = (
    # логин, роль профиля, имя, фамилия
    ('dev-student', UserProfile.Role.STUDENT, 'Дев', 'Ученик'),
    ('dev-teacher', UserProfile.Role.TUTOR, 'Дев', 'Учитель'),
    ('dev-parent', UserProfile.Role.PARENT, 'Дев', 'Родитель'),
)

# Название группы, в которой dev-student состоит у dev-teacher. Без неё
# половина экранов преподавателя пуста: группа — точка входа к ученику.
ГРУППА = 'dev-группа'

# Личное, что НЕ уходит каскадом за пользователем (ссылка на автора —
# `SET_NULL`). Сносим явно. Порядок значения не имеет: связи между ними
# каскадные.
ЛИЧНОЕ_СВЕРХ_КАСКАДА = (
    ('домашние задания', Assignment),
    ('занятия', Lesson),
    ('подборки', Collection),
    ('обратная связь', Feedback),
    ('записи об экспорте', ExportRecord),
)


def _олимпиады():
    """Число фактов справочника олимпиад — или None, если раздела нет.

    ⚠️ Импорт ЛЕНИВЫЙ и защищённый. `olympiads` — отдельное приложение со
    своими моделями (ADR 0063); команда обязана работать и там, где его
    ещё нет (старая база, урезанная сборка), а не падать на импорте.
    """
    try:
        from olympiads.models import Olympiad
    except Exception:                       # noqa: BLE001 — нет раздела, и ладно
        return None
    return Olympiad.objects.count()


class Command(BaseCommand):
    help = ('Удалить всех пользователей и всё личное с площадки dev, '
            'оставив банк задач и олимпиады. Работает только при SITE_ENV=dev.')

    def add_arguments(self, parser):
        parser.add_argument(
            '--yes', action='store_true',
            help='Выполнить на самом деле. Без флага печатается только план.')

    def handle(self, *args, **options):
        # ── Предохранитель 1: только площадка ────────────────────────────
        окружение = getattr(settings, 'SITE_ENV', 'prod')
        if окружение != 'dev':
            raise CommandError(
                'dev_scrub работает только при SITE_ENV=dev, а сейчас '
                'SITE_ENV=%r. Эта команда удаляет ВСЕХ пользователей: на бою '
                'её запуск означал бы потерю боевой базы.' % окружение)

        задач_до = Problem.objects.count()
        олимпиад_до = _олимпиады()
        людей_до = User.objects.count()

        # Что уйдёт каскадом — не перечисляем поимённо (46 связей на `User`),
        # но число людей называем: по нему видно масштаб.
        self.stdout.write('Площадка: SITE_ENV=%s' % окружение)
        self.stdout.write('  задач в банке:      %d' % задач_до)
        self.stdout.write('  олимпиад:           %s'
                          % ('нет раздела' if олимпиад_до is None else олимпиад_до))
        self.stdout.write('  пользователей:      %d (будут удалены все)' % людей_до)
        for подпись, модель in ЛИЧНОЕ_СВЕРХ_КАСКАДА:
            self.stdout.write('  %-18s  %d' % (подпись + ':', модель.objects.count()))

        # ── Предохранитель 2: без --yes только план ──────────────────────
        if not options['yes']:
            self.stdout.write(self.style.WARNING(
                '\nЭто ПЛАН, ничего не удалено. Запуск по-настоящему: '
                'manage.py dev_scrub --yes'))
            return

        # ── Пароль тестовых аккаунтов ────────────────────────────────────
        пароль = getattr(settings, 'DEV_ACCOUNTS_PASSWORD', '') or ''
        if not пароль.strip():
            raise CommandError(
                'DEV_ACCOUNTS_PASSWORD пуст. Задайте его в '
                '/srv/weconomics/dev/.env — иначе тестовые аккаунты вышли бы '
                'без пароля, а площадка закрыта только паролем nginx.')

        with transaction.atomic():
            # 1. Личное, что не уходит каскадом.
            снесено = {}
            for подпись, модель in ЛИЧНОЕ_СВЕРХ_КАСКАДА:
                снесено[подпись] = модель.objects.all().delete()[0]

            # 2. Люди. За ними каскадом уходят работы, попытки, события,
            #    группы (вместе с кодами приглашений), профили, достижения,
            #    прогресс, записи игры и тренировок олимпиад.
            людей_снесено = User.objects.all().delete()[0]

            # 3. Четыре тестовых аккаунта и связи между ними.
            #    ⚠️ Заводим ТЕМ ЖЕ способом, что настоящая регистрация:
            #    create_user + UserProfile с ролью. `User.role` подтянет
            #    `UserProfile.sync_user_role()` — руками его не трогаем.
            заведённые = {}
            for логин, роль_профиля, имя, фамилия in АККАУНТЫ:
                человек = User.objects.create_user(
                    username=логин, email='%s@example.invalid' % логин,
                    first_name=имя, last_name=фамилия)
                человек.set_password(пароль)
                человек.save()
                UserProfile.objects.update_or_create(
                    user=человек, defaults={'role': роль_профиля})
                человек.refresh_from_db()
                заведённые[логин] = человек

            # ⚠️ АДМИНИСТРАТОР ЗАВОДИТСЯ ОТДЕЛЬНО, И ВОТ ПОЧЕМУ.
            # `UserProfile.sync_user_role()` НАМЕРЕННО не трогает роль
            # суперпользователя («у него роль служебная»), поэтому через общий
            # цикл роль ему бы не проставилась вовсе и осталась бы значением
            # по умолчанию — `student`. Шапка тогда показывала бы админу меню
            # ученика. Ставим `User.role` явно — это единственное место, где
            # так можно, и причина записана здесь.
            админ = User.objects.create_superuser(
                username='dev-admin', email='dev-admin@example.invalid',
                password=пароль)
            админ.first_name, админ.last_name = 'Дев', 'Админ'
            админ.role = User.Role.TEACHER
            админ.save()
            UserProfile.objects.update_or_create(
                user=админ, defaults={'role': UserProfile.Role.TUTOR})
            заведённые['dev-admin'] = админ

            # Группа: без неё половина экранов преподавателя пуста, а ученик
            # не виден учителю вовсе. Код приглашения проставляет сама модель
            # (StudentGroup.save), своего генератора здесь нет.
            группа = StudentGroup.objects.create(
                name=ГРУППА, teacher=заведённые['dev-teacher'])
            группа.students.add(заведённые['dev-student'])

            # Связь родитель → ребёнок. Отдельная модель, а не поле профиля:
            # у родителя бывает несколько детей и наоборот. `created_by` —
            # кто выдал доступ к учебным данным ребёнка; в жизни это
            # репетитор, здесь тоже.
            ParentLink.objects.create(
                parent=заведённые['dev-parent'],
                student=заведённые['dev-student'],
                created_by=заведённые['dev-teacher'])

            # ── Инвариант: банк не пострадал ─────────────────────────────
            задач_после = Problem.objects.count()
            олимпиад_после = _олимпиады()
            if задач_после != задач_до:
                raise CommandError(
                    'ОТКАТ: задач было %d, стало %d. Значит у какой-то ссылки '
                    'на пользователя стоит CASCADE вместо SET_NULL, и чистка '
                    'уносит банк. Разберитесь до следующего запуска.'
                    % (задач_до, задач_после))
            if олимпиад_после != олимпиад_до:
                raise CommandError(
                    'ОТКАТ: олимпиад было %s, стало %s.'
                    % (олимпиад_до, олимпиад_после))

        self.stdout.write('')
        for подпись, число in снесено.items():
            self.stdout.write('  удалено %-18s %d' % (подпись + ':', число))
        self.stdout.write('  удалено людей и связанного: %d записей' % людей_снесено)
        self.stdout.write('')
        self.stdout.write('  задач в банке:  %d (было %d)' % (задач_после, задач_до))
        self.stdout.write('  олимпиад:       %s (было %s)'
                          % (олимпиад_после, олимпиад_до))
        self.stdout.write('  пользователей:  %d — %s'
                          % (User.objects.count(),
                             ', '.join(sorted(заведённые))))
        self.stdout.write('  группа «%s»: %s → %s'
                          % (ГРУППА, 'dev-teacher', 'dev-student'))
        self.stdout.write('  родитель: dev-parent → dev-student')
        self.stdout.write('  гость: аккаунт не нужен — это окно инкогнито')
        self.stdout.write(self.style.SUCCESS(
            'Готово. Пароль обоих аккаунтов — из DEV_ACCOUNTS_PASSWORD.'))
