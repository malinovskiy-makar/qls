# -*- coding: utf-8 -*-
"""Набор B измерителя (С14) — обратная генерация запросов. СТОИТ ДЕНЕГ.

Модель читает настоящую задачу и пишет три фразы, которыми репетитор искал бы
такую. Правильный ответ известен заранее — это та самая задача.

⚠️⚠️ ЖЁСТКОЕ ПРАВИЛО НАБОРА B. Нарушать нельзя, и оно записано здесь, а не
только в голове у того, кто набор заказывал:

    По набору B РАЗРЕШЕНО утверждать «вариант Б лучше варианта А».
    По набору B ЗАПРЕЩЕНО утверждать «наш поиск даёт качество 0,85».

Синтетика систематически ЗАВЫШАЕТ абсолютные цифры: nDCG@10 примерно на 0,2
против человеческой разметки. Относительный порядок систем при этом
сохраняется (корреляция Кендалла 0,73–0,92), поэтому сравнивать между собой
варианты формулы — можно, называть абсолютное качество поиска — нет. Для
абсолютных цифр есть набор C: живые формулировки владельца.

⚠️ `--dry-run` ПО УМОЛЧАНИЮ, БОЕВОЙ ПРОГОН — ТОЛЬКО ПО `--apply`. Регламент
слоя команд (`problems/management/commands/CLAUDE.md`) требует этого от любой
массовой команды; здесь причина ещё прямее — команда тратит деньги. Случайный
запуск обязан ничего не сделать, а не потратить бюджет.

⚠️ ФОРМАТ СРАЗУ ОБУЧАЮЩИЙ. В файле лежат `query`, `relevant_ids` и
`hard_negative_ids: null`. Тот же материал понадобится для дообучения модели
(уровень 5 `EMBEDDINGS.md`), и платить за генерацию второй раз незачем.

Запуск:
    manage.py build_eval_set_b                  # смета, ничего не тратит
    manage.py build_eval_set_b --limit 1000 --apply
"""
import random

from django.core.management.base import BaseCommand, CommandError

from problems.ai import core
from problems.eval_sets import DATA_DIR, save_eval_set
from problems.models import Problem
from problems.search_eval_metrics import EvalCase

ПРОФИЛЬ = 'search_query_backgen'

# ⚠️ ДЛИНУ МАССИВА СХЕМОЙ НЕ ЗАДАТЬ. Structured output Anthropic принимает у
# массива только `minItems: 0` или `minItems: 1`; `minItems: 3` и любой
# `maxItems` дают 400 ещё до генерации — на этом 28.08 упал пилот набора B:
#
#     output_config.format.schema: For 'array' type, 'minItems' values other
#     than 0 or 1 are not supported (got: [2, 5])
#
# Ограничение описано у Anthropic в разделе «Not supported» и обходу не
# подлежит. Поэтому «ровно три» держат два других слоя: требование в профиле
# промпта (`problems/ai/prompts.py`) и разбор ответа (`_разобрать_фразы`).
# Схема отвечает только за ФОРМУ — массив строк.
СХЕМА = {
    'type': 'object',
    'properties': {
        'queries': {
            'type': 'array',
            'items': {'type': 'string'},
        },
    },
    'required': ['queries'],
    'additionalProperties': False,
}

# Сколько фраз обязано быть в ответе. Держится промптом и разбором, не схемой.
ФРАЗ_НА_ЗАДАЧУ = 3


def _разобрать_фразы(данные):
    """Ровно три непустые фразы из ответа модели — или ValueError.

    Схемой этого не проверить (см. выше), а недобор молча испортил бы набор:
    часть задач оказалась бы представлена одной фразой вместо трёх, и
    сравнение вариантов формулы поехало бы на разном объёме материала.
    """
    фразы = (данные or {}).get('queries')
    if not isinstance(фразы, list):
        raise ValueError(f'queries не массив, а {type(фразы).__name__}')
    непустые = [ф.strip() for ф in фразы if isinstance(ф, str) and ф.strip()]
    if len(непустые) != ФРАЗ_НА_ЗАДАЧУ:
        raise ValueError(
            f'ожидалось {ФРАЗ_НА_ЗАДАЧУ} непустых фразы, получено '
            f'{len(непустые)} (элементов в ответе: {len(фразы)})')
    return непустые

# Сколько символов условия отдаём модели. Больше не нужно: заход к задаче
# виден по первым абзацам, а каждый лишний символ — деньги на каждой из
# тысячи задач.
СИМВОЛОВ_УСЛОВИЯ = 1800

# ── Смета ────────────────────────────────────────────────────────────────
#
# ⚠️ СМЕТА — ЭТО ВИЛКА, А НЕ ЧИСЛО, И ЭТО НЕ ОСТОРОЖНИЧАНЬЕ. Токенизатор
# Claude закрыт, посчитать точно нечем. Замер на 1 000 реальных условий банка
# токенизатором BGE-M3 (XLM-R) дал 3,76 символа на токен. Но XLM-R специально
# натаскан на многоязычность и на кириллице заметно экономнее большинства
# английских BPE; у модели ответа то же место обычно дороже. Поэтому нижняя
# граница считается по замеренному ratio, верхняя — по вдвое худшему.
#
# Одно число вместо вилки означало бы «я знаю то, чего не знаю», а решение о
# тратах принимается по нему.
СИМВОЛОВ_НА_ТОКЕН_ЗАМЕР = 3.76   # измерено на 1 000 условий банка (XLM-R)
ЗАПАС_ТОКЕНИЗАТОРА = 2.0         # во столько раз хуже в верхней границе
ТОКЕНОВ_ОТВЕТА = 120             # три короткие фразы плюс обвязка JSON

# ⚠️ ПЕРВЫЙ СИСТЕМНЫЙ БЛОК КЭШИРУЕТСЯ, И БЕЗ ЭТОГО СМЕТА ВРЁТ ВДВОЕ.
# `providers.py` вешает `cache_control: ephemeral` на блок №0 (ядро). Чтение
# из кэша стоит десятую часть тарифа, запись — тариф с четвертью. На тысяче
# обращений ядро — самая большая часть входа, и считать его полной ценой
# каждый раз значит завысить смету почти вдвое. Кэш держится, пока обращения
# идут подряд: прогон непрерывный, паузы между вызовами секунды.
ДОЛЯ_ЧТЕНИЯ_ИЗ_КЭША = 0.1
ДОЛЯ_ЗАПИСИ_В_КЭШ = 1.25


class Command(BaseCommand):
    help = ('Собрать эталонный набор B (обратная генерация запросов). '
            'ТРАТИТ ДЕНЬГИ: боевой прогон только с --apply.')

    def add_arguments(self, parser):
        parser.add_argument('--limit', type=int, default=1000,
                            help='Сколько задач взять (по умолчанию 1000).')
        parser.add_argument('--seed', type=int, default=20260828,
                            help='Зерно выборки: тот же seed — та же выборка.')
        parser.add_argument(
            '--scope', default='all', choices=['prod', 'all'],
            help='Откуда брать задачи: all — весь банк с вектором '
                 '(по умолчанию), prod — только видимое на сайте.')
        parser.add_argument('--apply', action='store_true',
                            help='БОЕВОЙ прогон: обращается к модели и тратит '
                                 'деньги. Без него — только смета.')
        parser.add_argument(
            '--max-cost', type=float, default=None,
            help='Жёсткий потолок расхода в долларах. Считается по '
                 'ФАКТИЧЕСКИМ токенам из ответов, а не по смете: смета — '
                 'оценка и может промахнуться, потолок обязан держать и '
                 'тогда. Превышение останавливает прогон.')
        parser.add_argument('--out', default=str(DATA_DIR / 'eval_set_b.json'))

    def handle(self, *args, **options):
        from catalog.semantic import index_queryset

        задачи = self._выборка(index_queryset(options['scope']),
                               options['limit'], options['seed'])
        if not задачи:
            raise CommandError('В выборке нет ни одной задачи.')

        смета = self._смета(задачи)
        self._показать_смету(задачи, смета, options)

        if not options['apply']:
            self.stdout.write(self.style.WARNING(
                '\nЭто СМЕТА. Ничего не потрачено и не записано.\n'
                'Боевой прогон: добавьте --apply'))
            return

        self._прогон(задачи, options)

    # ── внутреннее ────────────────────────────────────────────────────

    def _выборка(self, qs, limit, seed):
        """Случайные задачи с фиксированным зерном, по всем источникам.

        Выборка детерминированная: тот же seed даёт тот же набор задач, иначе
        повторный прогон стоил бы денег и дал бы другой эталон — сравнивать
        замеры между собой стало бы нельзя.

        Отбираются задачи с осмысленным по длине условием: на огрызке в
        полсотни символов модель напишет три одинаковые общие фразы, и мы
        заплатим за мусор.
        """
        ids = list(qs.exclude(statement='')
                   .filter(statement__isnull=False)
                   .values_list('id', flat=True))
        rng = random.Random(seed)
        rng.shuffle(ids)
        отобранные = []
        for пачка_начало in range(0, len(ids), 2000):
            пачка = ids[пачка_начало:пачка_начало + 2000]
            строки = dict(Problem.objects.filter(pk__in=пачка)
                          .values_list('id', 'statement'))
            for pid in пачка:
                текст = (строки.get(pid) or '').strip()
                if len(текст) < 200:
                    continue
                отобранные.append((pid, текст[:СИМВОЛОВ_УСЛОВИЯ]))
                if len(отобранные) >= limit:
                    return отобранные
        return отобранные

    def _смета(self, задачи):
        """Вилка стоимости: нижняя граница по замеру, верхняя — с запасом.

        Считается по трём частям входа отдельно, потому что стоят они разное:
        ядро кэшируется (0,1 тарифа на чтение), профиль и условие идут полной
        ценой каждое обращение.
        """
        from problems.ai.core import DEFAULT_MODEL, DEFAULT_PRICES
        from problems.ai.prompts import system_blocks

        ядро, профиль = system_blocks(ПРОФИЛЬ)[0], system_blocks(ПРОФИЛЬ)[1]
        n = len(задачи)
        цена_вход, цена_выход = DEFAULT_PRICES.get(DEFAULT_MODEL, (1.0, 5.0))

        def посчитать(симв_на_токен):
            ядро_т = len(ядро) / симв_на_токен
            профиль_т = len(профиль) / симв_на_токен
            условия_т = sum(len(т) for _, т in задачи) / симв_на_токен
            выход_т = ТОКЕНОВ_ОТВЕТА * n * (СИМВОЛОВ_НА_ТОКЕН_ЗАМЕР
                                            / симв_на_токен)
            # Ядро: один раз записывается в кэш, дальше читается из него.
            вход_экв = (ядро_т * ДОЛЯ_ЗАПИСИ_В_КЭШ
                        + ядро_т * ДОЛЯ_ЧТЕНИЯ_ИЗ_КЭША * (n - 1)
                        + профиль_т * n
                        + условия_т)
            return {
                'вход_экв': вход_экв,
                'выход': выход_т,
                'доллары': вход_экв / 1e6 * цена_вход + выход_т / 1e6 * цена_выход,
            }

        низ = посчитать(СИМВОЛОВ_НА_ТОКЕН_ЗАМЕР)
        верх = посчитать(СИМВОЛОВ_НА_ТОКЕН_ЗАМЕР / ЗАПАС_ТОКЕНИЗАТОРА)
        return {'модель': DEFAULT_MODEL, 'низ': низ, 'верх': верх}

    def _показать_смету(self, задачи, смета, options):
        низ, верх = смета['низ'], смета['верх']
        n = len(задачи)
        self.stdout.write('')
        self.stdout.write('── СМЕТА НАБОРА B ──')
        self.stdout.write(f'  Задач в выборке:       {n}')
        self.stdout.write(f'  Запросов на выходе:    {n * 3} (по 3 на задачу)')
        self.stdout.write(f'  Модель:                {смета["модель"]}')
        self.stdout.write(f'  Срез выборки:          {options["scope"]}')
        self.stdout.write(f'  Зерно (повторяемость): {options["seed"]}')
        self.stdout.write(
            f'  Токенов входа (экв.):  '
            f'{int(низ["вход_экв"]):,} … {int(верх["вход_экв"]):,}'
            .replace(',', ' '))
        self.stdout.write(
            f'  Токенов выхода:        '
            f'{int(низ["выход"]):,} … {int(верх["выход"]):,}'.replace(',', ' '))
        self.stdout.write(
            '  Ядро промпта идёт по кэшу (0,1 тарифа) — учтено.')
        self.stdout.write(self.style.WARNING(
            f'  ОЦЕНКА СТОИМОСТИ:      '
            f'${низ["доллары"]:.2f} … ${верх["доллары"]:.2f}'))
        self.stdout.write(
            f'  На задачу:             '
            f'${низ["доллары"] / n:.5f} … ${верх["доллары"] / n:.5f}')
        self.stdout.write(
            '  ⚠️ Это ОЦЕНКА: токенизатор модели закрыт, точно посчитать '
            'нечем.\n'
            '     Настоящий потолок держит --max-cost, он считает по '
            'фактическим\n'
            '     токенам из ответов и останавливает прогон.')

    def _прогон(self, задачи, options):
        предел = options.get('max_cost')
        случаи, ошибок, потрачено = [], 0, 0.0
        for н, (pid, текст) in enumerate(задачи, start=1):
            try:
                # ⚠️ ЕДИНСТВЕННАЯ ДВЕРЬ НАРУЖУ — core.run. Прямого обращения к
                # anthropic здесь нет и быть не должно: кэш, суточные лимиты и
                # учёт расхода живут только там (problems/ai/CLAUDE.md).
                # Наружу уходит ТОЛЬКО текст задачи: полей профиля
                # пользователя в запросе нет ни одного.
                итог = core.run(ПРОФИЛЬ, текст, СХЕМА, user=None,
                                check_limit=False)
            except Exception as ошибка:
                ошибок = self._отказ(pid, ошибка, ошибок, н)
                continue

            # ⚠️ `usage` — СЛОВАРЬ, а не объект (см. `core._log`). Первая
            # версия читала его через getattr('cost') и всегда получала ноль:
            # счётчик денег молча показывал $0.00 на любом прогоне. Стережёт
            # `test_настоящий_расход_попадает_в_итог`.
            потрачено += float((итог.usage or {}).get('cost_usd', 0.0) or 0.0)

            # Потолок считается по ФАКТИЧЕСКИМ токенам из ответа, а не по
            # смете: смета — оценка и может промахнуться, потолок обязан
            # держать и тогда.
            if предел is not None and потрачено > предел:
                raise CommandError(
                    f'Бюджет исчерпан: потрачено ${потрачено:.4f} при пределе '
                    f'${предел:.4f} на {н}-й задаче из {len(задачи)}. '
                    f'Прогон остановлен, набор не записан. Поднимите '
                    f'--max-cost или уменьшите --limit.')

            # ⚠️ РАЗБОР ПОСЛЕ УЧЁТА ДЕНЕГ, А НЕ ДО. Обращение уже оплачено,
            # даже если ответ негодный. Пропусти негодные мимо счётчика — и
            # --max-cost перестанет держать потолок ровно на тех прогонах,
            # где модель сбивается чаще всего.
            try:
                фразы = _разобрать_фразы(итог.data)
            except ValueError as ошибка:
                ошибок = self._отказ(pid, ошибка, ошибок, н)
                continue

            случаи.extend(
                EvalCase(query=фраза, relevant_ids={pid},
                         meta={'source_problem_id': pid})
                for фраза in фразы)
            if н % 50 == 0:
                self.stdout.write(
                    f'  {н}/{len(задачи)} задач, {len(случаи)} запросов, '
                    f'ошибок {ошибок}, потрачено ${потрачено:.3f}')

        путь = save_eval_set(
            options['out'], name='B', spent_usd=потрачено,
            description='Обратная генерация: модель написала фразы, которыми '
                        'репетитор искал бы эту задачу. Набор СРАВНЕНИЯ '
                        'вариантов, не набор абсолютных цифр.',
            cases=случаи, mode='text',
            warnings=[
                'РАЗРЕШЕНО: «вариант Б лучше варианта А». ЗАПРЕЩЕНО: «поиск '
                'даёт качество 0,85». Синтетика завышает nDCG@10 примерно на '
                '0,2 против человеческой разметки; относительный порядок '
                'систем при этом сохраняется (Кендалл 0,73–0,92).',
                f'Выборка детерминирована: seed={options["seed"]}, '
                f'срез={options["scope"]}. Тот же seed даёт тот же набор.',
                f'Ошибок при генерации: {ошибок} из {len(задачи)} задач.',
            ])
        self.stdout.write(self.style.SUCCESS(
            f'\nГотово: {len(случаи)} запросов по {len(задачи) - ошибок} '
            f'задачам, ошибок {ошибок}.\nЗаписано: {путь}'))

    def _отказ(self, pid, ошибка, ошибок, н):
        """Зарегистрировать отказ по задаче; вернуть новый счётчик.

        Общий путь для обеих причин — обращение не удалось и ответ не разобран:
        считаются они одинаково, и порог остановки прогона у них общий.
        """
        ошибок += 1
        if ошибок <= 3:
            self.stdout.write(self.style.ERROR(f'  задача #{pid}: {ошибка}'))
        if ошибок >= 20 and ошибок >= н // 2:
            raise CommandError(
                f'Слишком много ошибок ({ошибок} из {н}) — '
                f'останавливаюсь, чтобы не жечь бюджет впустую.')
        return ошибок
