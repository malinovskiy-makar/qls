from __future__ import annotations

import re

#: `[7] Решение:` в самом начале условия — служебный номер задачи из
#: исходного Overleaf-сборника плюс заголовок раздела решения.
_LEAK_PREFIX_RE = re.compile(r'^\s*\[\d+\]\s*Решени[ея]\s*:?', re.IGNORECASE)
#: Заголовок решения без номера, тоже в начале поля.
_BARE_PREFIX_RE = re.compile(r'^\s*Решени[ея]\s*:', re.IGNORECASE)

CODE = 'SOL-LEAK'


def detect_solution_leak(raw_statement):
    """`(есть_утечка, объяснение)` для сырого текста условия."""
    text = raw_statement or ''
    if _LEAK_PREFIX_RE.match(text):
        return True, ('условие начинается с маркера «[N] Решение:» — по замеру '
                      'по всему Archive 3 (47 задач) настоящего условия в поле '
                      'нет, там лежит текст решения; нужен исходник, машиной '
                      'не восстанавливается')
    if _BARE_PREFIX_RE.match(text):
        return True, ('условие начинается с заголовка «Решение:» — в поле '
                      'условия лежит решение, нужен исходник')
    return False, ''
