# -*- coding: utf-8 -*-
"""Лексический отбор шорт-листа словаря терминов (Б1, прогон v2).

Поле `econ_concepts` в прогоне обогащения выбирается моделью из ЗАКРЫТОГО
шорт-листа ~40 терминов, поданного вместе с текстом задачи. Отбирать эти
40 «по теме задачи» нельзя: темы нет у 54,7 % задач и у 100 % новых
источников, а тему как раз и считает вызов, для которого шорт-лист
готовится, — замкнутый круг. Поэтому отбор ЛЕКСИЧЕСКИЙ и делается кодом
до вызова модели.

Как это устроено.

1. `compute_document_frequencies()` один раз проходит по всему корпусу и
   считает документную частоту каждого из 1 772 терминов словаря
   (`problems/econ_terms.py`). Термин «встречен» в тексте, если найдена
   его каноническая форма, любой русский синоним, любая словоформа из
   четырёх падежей, английский эквивалент, ИЛИ многобуквенное однозначное
   обозначение — см. `matched_terms()`.
2. `save_df_cache()` / `load_df_cache()` кладут и читают результат в
   `data/econ_terms_df.json`, чтобы не считать это на каждом прогоне.
3. `shortlist_for(text, k=40)` находит все термины, встречающиеся в
   КОНКРЕТНОМ тексте, сортирует по возрастанию документной частоты
   (редкие вперёд — они различают задачи) и отдаёт первые `k`.

⚠️ ОБОЗНАЧЕНИЯ — ОТДЕЛЬНЫЙ И ОГРАНИЧЕННЫЙ КАНАЛ. Однобуквенные (`P`, `S`,
`D`, `I`, `R`, `C`, `π`...) в отбор не участвуют вообще, даже если словарь
считает их однозначными (`p`, `I`, `W`, `Π` формально `auto_normalize:
true`, но без контекста абзаца это всё равно гадание — предупреждение уже
объяснено в `problems/econ_terms.py`). Обозначения, у которых в обратном
индексе словаря больше одного канонического термина (`auto_normalize:
false`), тоже не участвуют — это тот же принцип, что и в самом словаре,
просто применённый на уровень раньше. Оба правила проверяются ГЛОБАЛЬНО
по обратному индексу словаря, а не по списку обозначений самого термина:
обозначение может стать неоднозначным из-за СОВСЕМ ДРУГОГО термина.

⚠️ ОТБОР ДЕТЕРМИНИРОВАН. Один и тот же текст всегда даёт один и тот же
шорт-лист: сортировка — по (частота, каноническое имя), без случайности.

⚠️ СОВПАДЕНИЕ ФРАЗ — ПО ГРАНИЦАМ СЛОВ, А НЕ ПОДСТРОКОЙ. Наивный `in`
находил бы «рост» внутри «прирост». Текст токенизируется на слова
(тире всех видов сведено к одному знаку, внутренний дефис оставлен —
«Куна-Таккера» остаётся одним токеном; см. `normalize_dashes()`), из токенов строятся n-граммы длиной до максимальной фразы
словаря (7 слов) и проверяются по словарю фраз. Обозначения (`SOC`,
`PPF`...) — короткие и малоупотребимые в обычном тексте, поэтому для них
осознанно оставлена более простая подстрочная проверка, регистрозависимая
(экономическое обозначение регистр не меняет: `MC` — не то же самое, что
«мс» где-то в слове).
"""
import json
import re
from functools import lru_cache
from pathlib import Path

from django.conf import settings

from problems import econ_terms

DF_FILE = 'econ_terms_df.json'

# Меньше — добираем ядром до этого числа (см. shortlist_for). Больше — не
# отдаём вовсе, даже если нашлось больше: k управляет верхней границей.
MIN_SHORTLIST = 15
DEFAULT_K = 40

OLYMPIC_CORE_PRIORITY = 'олимпиадное ядро'

_TOKEN_RE = re.compile(
    r'[a-zA-Zа-яА-ЯёЁ0-9]+(?:-[a-zA-Zа-яА-ЯёЁ0-9]+)*')
_HYPHEN_RE = re.compile(r'-')

# ---------------------------------------------------------------------------
# Фаза 0 (03.09.2026): ТИРЕ ВСЕХ ВИДОВ — ОДИН ЗНАК ПРИ СОПОСТАВЛЕНИИ.
#
# Токенизатор понимал дефис `-` и короткое тире `–`, но не длинное `—`. Из-за
# этого «Кобба—Дугласа» не находилось в тексте никогда: длинное тире не входило
# в класс символов токена, поэтому текст распадался на четыре токена
# («производственная», «функция», «кобба», «дугласа»), а ключ словаря оставался
# трёхсловным («производственная функция кобба—дугласа») — совпасть они не
# могли в принципе.
#
# Это класс, а не единичный случай: длинное тире стоит в именах моделей и
# теорем (Манделла—Флеминга, Столпера—Сэмюэльсона, Хекшера—Олина,
# Блэка—Шоулза, Модильяни—Миллера, Маршалла—Лернера), и у 13 из 15 таких
# терминов словаря дефисного варианта НЕТ вовсе.
#
# Правится ТОКЕНИЗАТОР, а не словарь: знак приводится к одному виду с ОБЕИХ
# сторон — и в тексте задачи, и в строке термина. Термин, записанный через
# «—», находится в тексте с «-», и наоборот.
#
# ⚠️ ГРАНИЦЫ СЛОВ НЕ МЕНЯЮТСЯ. Нормализация подменяет знак, а не склеивает
# токены: «Куна-Таккера» остаётся одним составным термином, а обрезки «куна» и
# «таккера» терминами не становятся. Пунктуационное тире между пробелами
# («Цена — это…») соседние слова в один токен не сливает: пробелы остаются
# пробелами. Оба правила проверены отдельными тестами в
# `DashNormalizationTests`.
#
# Набор знаков — все, которыми на практике пишут тире и дефис в наших
# источниках и в математической вёрстке: юникодные дефисы, тире и знак минус.
# ---------------------------------------------------------------------------
_DASH_TRANSLATION = {
    ord('‐'): '-',   # HYPHEN
    ord('‑'): '-',   # NON-BREAKING HYPHEN
    ord('‒'): '-',   # FIGURE DASH
    ord('–'): '-',   # EN DASH — короткое тире
    ord('—'): '-',   # EM DASH — длинное тире
    ord('―'): '-',   # HORIZONTAL BAR
    ord('−'): '-',   # MINUS SIGN
}


def normalize_dashes(text):
    """Все виды тире, дефиса и знак минус — к одному `-` (U+002D)."""
    return (text or '').translate(_DASH_TRANSLATION)

# ---------------------------------------------------------------------------
# Стоп-лист «сквозных» понятий (Фаза A задания сессии 02.09.2026): термины,
# которые встречаются в 13%+ всего корпуса (замер по data/econ_terms_df.json,
# 02.09.2026) — «цена», «спрос», «функция» есть буквально в любой
# микрозадаче независимо от темы.
#
# ⚠️ ЭТОТ СПИСОК ВЛИЯЕТ ТОЛЬКО НА ДОБОР В `shortlist_for()`, НЕ НА
# `matched_terms()`. Первая версия фильтровала оба места и сломала
# `WorkedExamplesShortlistTests`: рабочий пример A ядра вызова 1
# (`prompts_v2.WORKED_EXAMPLES`) прямо просит «Найдите равновесие» и
# объявляет «равновесие»/«спрос» законными `econ_concepts` — задача, где
# именно ЭТО и есть суть вопроса, обязана иметь право их получить.
# Буквальное совпадение в тексте — настоящий сигнал, даже если термин
# частый. Хуже был не литеральный матч, а ДОБОР, который вставлял эти же
# термины НАУГАД, когда их в тексте не было вовсе (сортировка по УБЫВАНИЮ
# частоты в `shortlist_for()` выбирает САМЫЕ общие термины первыми, когда
# найдено меньше MIN_SHORTLIST) — фильтр стоит именно там.
#
# Список — не порог по частоте (например, «монополист» тоже частый — 5,7%
# корпуса, — но это специфичное понятие темы, а не общая лексика), а ручная
# сверка верхних по частоте терминов словаря: чистая математическая/
# структурная лексика («функция», «уравнение», «величина», «количество»,
# «возможность») и базовые экономические существительные, которые есть в
# формулировке практически любой микро- или макрозадачи независимо от того,
# какая модель в ней используется («цена», «спрос», «предложение», «рынок»,
# «фирма», «товар», «издержки», «производство», «прибыль», «выпуск», «доход»,
# «стоимость», «период», «ставка», «рост», «экономика», «равновесие»,
# «деньги», «общие издержки»).
# ---------------------------------------------------------------------------
STOP_TERMS = frozenset({
    'цена', 'спрос', 'количество', 'рынок', 'издержки', 'функция', 'фирма',
    'товар', 'производство', 'предложение', 'прибыль', 'общие издержки',
    'выпуск', 'ставка', 'рост', 'экономика', 'доход', 'равновесие',
    'уравнение', 'стоимость', 'период', 'величина', 'возможность', 'деньги',
})


def _tokenize(text, split_hyphens=False):
    """`split_hyphens=True` — «фирма-монополист» становится двумя токенами
    («фирма», «монополист»), а не одним. Нужно ОБОИМИ способами: базовая
    токенизация защищает составные термины словаря («условие Куна-Таккера»,
    «производственная функция Кобба-Дугласа» — см. докстринг модуля), а
    аппозитивный дефис («фирма-монополист», «страна-экспортёр» — два разных
    самостоятельных слова, просто так принято писать по-русски) от неё же и
    страдает: словоформа внутри склеенного токена никогда не совпадёт ни с
    одной фразой словаря. `matched_terms()` прогоняет оба варианта и берёт
    объединение — см. её докстринг ниже.

    Тире всех видов приводится к одному знаку ДО разбора — см.
    `normalize_dashes()`."""
    tokens = _TOKEN_RE.findall(normalize_dashes(text).lower())
    if not split_hyphens:
        return tokens
    out = []
    for token in tokens:
        out.extend(part for part in _HYPHEN_RE.split(token) if part)
    return out


@lru_cache(maxsize=1)
def _phrase_index():
    """Словарь фраз: 'фраза в нижнем регистре' -> {канонические термины}.

    Плюс максимальная длина фразы в словах — n-граммы длиннее её строить
    незачем.

    ⚠️ КЛЮЧ СТРОИТСЯ ТЕМ ЖЕ ТОКЕНИЗАТОРОМ, ЧТО И ТЕКСТ ЗАДАЧИ. Раньше ключом
    была строка термина как есть (`phrase.strip().lower()`), а искалась в ней
    n-грамма из токенов текста — две разные разметки, которые совпадали только
    случайно. Расходились они всюду, где в термине стоит знак, который
    токенизатор выбрасывает или трактует иначе:

    * `коэффициент «цена—прибыль»` — ключ нёс кавычки-ёлочки, в тексте их
      никогда нет (токенизатор их отбрасывает), совпадения не было ни разу;
    * `первым поступил — первым выбыл` — тире между пробелами: после одной
      лишь замены знака ключ дал бы пять «слов» по `split()`, а текст — четыре
      токена.

    Прогон фразы через `_tokenize()` снимает оба случая разом: обе стороны
    размечаются одинаково по построению, а не по совпадению. По той же причине
    `max_words` считается по числу ТОКЕНОВ, а не по `phrase.split()`.
    """
    index = {}
    max_words = 1
    for term in econ_terms.terms():
        canonical = term['canonical']
        phrases = {canonical}
        phrases.update(term.get('synonyms') or [])
        phrases.update((term.get('word_forms') or {}).values())
        phrases.update(term.get('english') or [])
        for phrase in phrases:
            tokens = _tokenize(phrase or '')
            if not tokens:
                continue
            index.setdefault(' '.join(tokens), set()).add(canonical)
            if len(tokens) > max_words:
                max_words = len(tokens)
    return index, max_words


@lru_cache(maxsize=1)
def _notation_index():
    """Обозначение (регистрозависимо) -> единственный канонический термин.

    Строится из ГЛОБАЛЬНОГО обратного индекса словаря
    (`econ_terms.notation_index()`), а не из списков обозначений отдельных
    терминов — см. предупреждение в докстринге модуля.
    """
    index = {}
    for symbol, slot in econ_terms.notation_index().items():
        symbol = (symbol or '').strip()
        if len(symbol) <= 1:
            continue
        if not slot.get('auto_normalize'):
            continue
        # Знак тире нормализуется и здесь: словарь несёт `AD-AS` и `AD–AS`
        # как два разных обозначения одного и того же, а в тексте задачи
        # встречается ещё и `AD—AS`. Регистр при этом НЕ трогаем — см.
        # докстринг модуля.
        index[normalize_dashes(symbol)] = slot['terms'][0]
    return index


def matched_terms(text):
    """Множество канонических терминов, найденных в тексте.

    Фраза ищется ДВАЖДЫ — по базовой токенизации (составные термины словаря
    вроде «условие Куна-Таккера» остаются целыми) и по токенизации с
    разрезанным аппозитивным дефисом («фирма-монополист» → «фирма» +
    «монополист») — результаты объединяются. См. докстринг `_tokenize()`.

    ⚠️ STOP_TERMS ЗДЕСЬ НЕ ФИЛЬТРУЕТСЯ — сознательно, вопреки первому
    инстинкту. «Спрос» и «равновесие» технически частые (30% и 8% корпуса),
    но остаются самостоятельными экономическими понятиями: рабочий пример A
    ядра вызова 1 (`prompts_v2.WORKED_EXAMPLES`) прямо просит найти
    равновесие и объявляет «спрос»/«равновесие» законными `econ_concepts`
    — задача, где именно ЭТО и есть суть вопроса, обязана иметь право их
    получить. Буквальное совпадение в тексте — настоящий сигнал, даже если
    термин частый. Хуже был не литеральный матч, а ДОБОР (см.
    `shortlist_for()`), который вставлял эти же термины НАУГАД, когда их в
    тексте не было вовсе, — фильтр стоит именно там.
    """
    text = text or ''
    found = set()

    phrase_index, max_words = _phrase_index()
    for tokens in (_tokenize(text), _tokenize(text, split_hyphens=True)):
        n = len(tokens)
        for start in range(n):
            limit = min(max_words, n - start)
            for length in range(1, limit + 1):
                phrase = ' '.join(tokens[start:start + length])
                terms = phrase_index.get(phrase)
                if terms:
                    found.update(terms)

    normalized = normalize_dashes(text)
    for symbol, canonical in _notation_index().items():
        if symbol in normalized:
            found.add(canonical)

    return found


def compute_document_frequencies(texts):
    """Документная частота термина = число ДОКУМЕНТОВ, где он встречен.

    `texts` — произвольный итератор строк (одна строка = условие +
    подпункты одной задачи). Повтор термина внутри одного документа
    считается один раз.

    Возвращает `(df, found_counts)`: `df` — словарь каноническое имя ->
    число документов; `found_counts` — список «сколько терминов нашлось»
    по каждому документу, по порядку — материал для инвариантов Б1
    (`corpus_invariants`).
    """
    df = {}
    found_counts = []
    for text in texts:
        found = matched_terms(text)
        found_counts.append(len(found))
        for canonical in found:
            df[canonical] = df.get(canonical, 0) + 1
    return df, found_counts


def corpus_invariants(found_counts):
    """Медиана и доли для отчёта по всему корпусу (печатает Б1-команда)."""
    if not found_counts:
        return {'median': 0, 'share_below_15': 0.0, 'share_above_40': 0.0}
    counts = sorted(found_counts)
    n = len(counts)
    mid = n // 2
    if n % 2:
        median = counts[mid]
    else:
        median = (counts[mid - 1] + counts[mid]) / 2
    below = sum(1 for c in counts if c < MIN_SHORTLIST) / n
    above = sum(1 for c in counts if c > DEFAULT_K) / n
    return {'median': median, 'share_below_15': below, 'share_above_40': above}


def df_cache_path():
    return Path(settings.BASE_DIR) / 'data' / DF_FILE


def save_df_cache(df, path=None):
    path = path or df_cache_path()
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(df, fh, ensure_ascii=False, indent=1, sort_keys=True)


def load_df_cache(path=None):
    path = path or df_cache_path()
    with open(path, encoding='utf-8') as fh:
        return json.load(fh)


def shortlist_for(text, k=DEFAULT_K, df=None):
    """Шорт-лист из максимум `k` терминов для конкретного текста задачи.

    Редкие термины (низкая документная частота — они различают задачи)
    идут первыми. Если нашлось меньше `MIN_SHORTLIST` (15) — добор
    самыми частыми терминами олимпиадного ядра, которых в шорт-листе ещё
    нет, до 15 (не до `k` — цель добора «дать модели из чего выбирать»,
    а не растянуть список).
    """
    if df is None:
        df = load_df_cache()

    found = matched_terms(text)
    ranked = sorted(found, key=lambda name: (df.get(name, 0), name))
    shortlist = ranked[:k]

    if len(shortlist) < MIN_SHORTLIST:
        chosen = set(shortlist)
        core_terms = [t['canonical'] for t in econ_terms.terms()
                      if t.get('priority') == OLYMPIC_CORE_PRIORITY
                      and t['canonical'] not in STOP_TERMS]
        core_ranked = sorted(core_terms,
                             key=lambda name: (-df.get(name, 0), name))
        for name in core_ranked:
            if len(shortlist) >= MIN_SHORTLIST:
                break
            if name in chosen:
                continue
            shortlist.append(name)
            chosen.add(name)

    return shortlist
