def call2_user_text(problem_text, given, find, solution, answer,
                    topic_primary_name='', task_nature=''):
    """`topic_primary_name`/`task_nature` — контекст из вызова 1 (Фаза 5,
    2026-09-01): без него вызов 2 заново решает «задача это или нет», не
    зная, что уже решил вызов 1. `topic_primary_name` — РАЗРЕШЁННОЕ имя
    темы (`taxonomy.theme_name_from_id`), не голый id — у вызова 2 в ядре
    нет дерева тем, id без расшифровки ему ничего не скажет.
    """
    parts = [
        'ЗАДАЧА (условие с подпунктами):\n%s' % problem_text,
        'ГЛАВНАЯ ТЕМА (из первого разбора): %s' % (topic_primary_name or '—'),
        'ХАРАКТЕР ЗАДАЧИ (из первого разбора): %s' % (task_nature or '—'),
        'ДАНО (из первого разбора): %s' % (given or '—'),
        'НАЙТИ (из первого разбора): %s' % (find or '—'),
    ]
    if answer:
        parts.append('ОТВЕТ: %s' % answer)
    if solution:
        parts.append('РЕШЕНИЕ:\n%s' % solution)
    else:
        parts.append('РЕШЕНИЯ НЕТ — верни `plot` и `hints` как null.')
    return '\n\n'.join(parts)


