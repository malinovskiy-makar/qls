def call2_user_text(problem_text, given, find, solution, answer):
    parts = [
        'ЗАДАЧА (условие с подпунктами):\n%s' % problem_text,
        'ДАНО (из первого разбора): %s' % (given or '—'),
        'НАЙТИ (из первого разбора): %s' % (find or '—'),
    ]
    if answer:
        parts.append('ОТВЕТ: %s' % answer)
    if solution:
        parts.append('РЕШЕНИЕ:\n%s' % solution)
    else:
        parts.append('РЕШЕНИЯ НЕТ — верни `plot` и `hints` как null.')
    return '\n\n'.join(parts)


