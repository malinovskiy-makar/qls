def call1_core(with_concepts=True):
    substitutions = {
        'taxonomy_tree': taxonomy.tree_text(),
        'task_nature': ', '.join(TASK_NATURE),
        'features_1': ', '.join(FEATURES_1),
        'topic_confidence': ', '.join(TOPIC_CONFIDENCE),
        'concepts_head_suffix': (', понятия из словаря' if with_concepts
                                 else ''),
        'visual_elements_note': VISUAL_ELEMENTS_NOTE,
    }
    head = CALL1_CORE_HEAD % substitutions
    lines = []
    n = 1
    for name, description, needs_concepts in CALL1_FIELDS:
        if needs_concepts and not with_concepts:
            continue
        lines.append('%d. `%s` %s' % (n, name, description % substitutions))
        n += 1
    tail = CALL1_CORE_TAIL % {
        'worked_examples': _worked_examples(with_concepts),
    }
    return head + '\n'.join(lines) + '\n' + tail


