# Схемы ответа. ⚠️ Верхние границы массивов — ТОЛЬКО текстом промпта выше,
# см. предупреждение в шапке файла. `strict: true` у OpenAI требует, чтобы
# ВСЕ свойства были в `required` — необязательные поля (`plot`, `hints`,
# `topics_secondary` пустой и т.п.) оформлены как nullable, а не отсутствующие.
# ---------------------------------------------------------------------------

def call1_schema(with_concepts=True):
    required = [
        'topic_primary', 'topics_secondary', 'tags', 'given', 'find',
        'task_nature', 'features_1', 'topic_confidence',
    ]
    # ⚠️ ИДЕНТИФИКАТОРЫ, НЕ НАЗВАНИЯ — диета префикса (Б4-2, 31.08.2026).
    # Полные названия остаются в дереве текста ядра (tree_text), в enum
    # схемы — только короткие id. Замер показал: `enum` из 344 полных
    # названий стоит непропорционально дороже своего текста (см. taxonomy.py
    # docstring про короткие идентификаторы) — вероятно, движок ограниченной
    # генерации разворачивает `enum` во внутреннюю грамматику, чей размер
    # зависит от длины строк-значений, а не только от общего числа символов.
    properties = {
        'topic_primary': {'type': 'string', 'enum': list(taxonomy.theme_ids())},
        'topics_secondary': {
            'type': 'array', 'minItems': 0,
            'items': {'type': 'string', 'enum': list(taxonomy.theme_ids())},
        },
        'tags': {
            'type': 'array', 'minItems': 1,
            'items': {'type': 'string', 'enum': list(taxonomy.tag_ids())},
        },
        'given': {'type': 'string'},
        'find': {'type': 'string'},
        'task_nature': {'type': 'string', 'enum': list(TASK_NATURE)},
        'features_1': {'type': 'array', 'minItems': 0,
                       'items': {'type': 'string', 'enum': list(FEATURES_1)}},
        'topic_confidence': {'type': 'string', 'enum': list(TOPIC_CONFIDENCE)},
    }
    if with_concepts:
        required += ['econ_concepts', 'concepts_offlist']
        properties['econ_concepts'] = {'type': 'array', 'minItems': 0,
                                       'items': {'type': 'string'}}
        properties['concepts_offlist'] = {'type': 'array', 'minItems': 0,
                                          'items': {'type': 'string'}}
    return {
        'type': 'object',
        'additionalProperties': False,
        'required': required,
        'properties': properties,
    }


