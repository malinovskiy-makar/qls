"""Особенности задачи: канонический список, кто их считает, витрина каталога.

⚠️ ЕДИНСТВЕННАЯ ТОЧКА ПРАВДЫ ПО ОСОБЕННОСТЯМ. Канон — `claude/API_RUN_MASTER_20260830.md`
§6 с правкой владельца 01.09.2026: особенностей ровно ДВЕНАДЦАТЬ, шесть считает
модель и шесть считает код. «Реальные данные» и «Нестандартный поворот» убраны
владельцем и здесь не появляются.

Хранение двухслойное, и слои не равноправны:

* **Связь `ProblemFeature`** — источник правды. Все двенадцать, у каждой записи
  видно, кто её поставил (`source`: модель, код или оба).
* **`Problem.features`** (JSON из трёх ключей `graph`/`table`/`proof`) — ВИТРИНА
  каталога, которую редизайн уже читает фильтрами. Она НЕ хранит нового факта:
  пересчитывается из связи функцией `catalog_view()` ниже и только ею.

Витрина не равна связи по смыслу: «есть график» в фильтре — это объединение
трёх разных особенностей, а не одна из них. Поэтому два слоя, а не один.
"""

# Кто считает особенность. `both` в справочнике не бывает — это значение
# появляется у КОНКРЕТНОЙ связи, когда модель и код сошлись на одной задаче
# (так устроено «Графическое решение», решение владельца 02.09.2026).
BY_MODEL = 'model'
BY_CODE = 'code'
BY_BOTH = 'both'

SOURCE_CHOICES = [
    (BY_MODEL, 'Поставила модель'),
    (BY_CODE, 'Посчитал код'),
    (BY_BOTH, 'Модель и код сошлись'),
]

# (ключ, подпись, кто считает). Порядок — порядок показа.
CATALOG_FEATURES = (
    # ── шесть от модели (problems/enrich/prompts_v2.py::FEATURES_1) ──
    ('графическое_решение', 'Графическое решение', BY_MODEL),
    ('нужен_график_в_ответе', 'Требуется построить график', BY_MODEL),
    ('на_доказательство', 'На доказательство', BY_MODEL),
    ('целочисленность_или_дискретный_выбор', 'Целочисленность или дискретный выбор', BY_MODEL),
    ('параметры', 'Параметры', BY_MODEL),
    ('бизнесовое', 'Бизнесовое', BY_MODEL),
    # ── шесть от кода ──
    ('на_английском', 'На английском', BY_CODE),
    ('с_реальной_олимпиады', 'С реальной олимпиады', BY_CODE),
    ('график_в_условии', 'График в условии', BY_CODE),
    ('табличка_в_условии', 'Табличка в условии', BY_CODE),
    ('многопунктовая', 'Многопунктовая', BY_CODE),
    ('есть_разбалловка', 'Есть разбалловка', BY_CODE),
)

MODEL_KEYS = tuple(k for k, _l, by in CATALOG_FEATURES if by == BY_MODEL)
CODE_KEYS = tuple(k for k, _l, by in CATALOG_FEATURES if by == BY_CODE)
ALL_KEYS = tuple(k for k, _l, _by in CATALOG_FEATURES)

# ---------------------------------------------------------------------------
# Витрина каталога
# ---------------------------------------------------------------------------

# Три ключа фильтра каталога (`catalog.filters.FEATURES`) ← какие особенности
# их зажигают. Правило владельца 06.09.2026 (карточка Notion «Разметить
# характер задачи и особенности»): «есть график» в фильтре — это и график в
# условии, и график в решении, и требование построить график, потому что
# ученик, ставящий этот фильтр, ищет задачу «про графики», а не конкретную
# из трёх ситуаций.
CATALOG_VIEW_MAP = {
    'graph': ('графическое_решение', 'нужен_график_в_ответе', 'график_в_условии'),
    'table': ('табличка_в_условии',),
    'proof': ('на_доказательство',),
}

#: Подписи ключей ВИТРИНЫ — для бейджиков на карточке задачи. Отдельно от
#: подписей в `CATALOG_FEATURES`, потому что говорят о другом: «Есть график»
#: объединяет три особенности, а «График в условии» — одна из них.
CATALOG_VIEW_LABELS = {
    'graph': 'Есть график',
    'table': 'Есть таблица',
    'proof': 'Требует доказательства',
}

# ⚠️ ПОРОГ ПОКАЗА В КАТАЛОГЕ. Особенность, привязка для которой ещё не
# собрана, в фильтр не выводится: пустой фильтр хуже отсутствующего — он
# обещает отбор и возвращает ноль. Решение владельца 07.09.2026 про
# «С реальной олимпиады»: показывать, когда признак есть не менее чем у
# 10 % активных задач. Проверяется ровно в одном месте —
# `catalog_visible_keys()` ниже.
MIN_CATALOG_COVERAGE = 0.10

# Особенности, которые ждут порога покрытия. Остальные показываются всегда:
# их считает код по данным, которые в банке уже есть целиком.
COVERAGE_GATED = ('с_реальной_олимпиады',)


def catalog_view(feature_keys):
    """Ключи особенностей задачи → витрина каталога (`Problem.features`).

    ⚠️ ЕДИНСТВЕННАЯ ФУНКЦИЯ, КОТОРАЯ СТРОИТ ВИТРИНУ. Любой другой способ
    получить `Problem.features` — это второй источник правды и рассинхрон;
    `problems/tests/test_enrich_features.py` краснеет, если витрина в базе
    разошлась со связью.
    """
    keys = set(feature_keys or ())
    return [view_key
            for view_key, sources in CATALOG_VIEW_MAP.items()
            if keys.intersection(sources)]


def catalog_visible_keys(coverage):
    """Какие особенности показывать в фильтре при данном покрытии.

    `coverage` — словарь «ключ особенности → доля активных задач, у которых
    она стоит» (0..1). Особенность из `COVERAGE_GATED` показывается, только
    когда её доля не ниже `MIN_CATALOG_COVERAGE`.
    """
    visible = []
    for key in ALL_KEYS:
        if key in COVERAGE_GATED and (coverage or {}).get(key, 0.0) < MIN_CATALOG_COVERAGE:
            continue
        visible.append(key)
    return tuple(visible)


# ---------------------------------------------------------------------------
# Характер задачи: `task_nature` прогона → `Problem.character` каталога
# ---------------------------------------------------------------------------

# Решение владельца 07.09.2026: «теоретическая» уходит в «качественная».
# Проверено глазами на десяти случайных задачах — это утверждения на
# понимание и «верно/неверно», а не алгебраические выкладки.
CHARACTER_BY_NATURE = {
    'расчётная': 'quant',
    'качественная': 'qual',
    'теоретическая': 'qual',
    'не_задача': '',
}


def character_for(task_nature):
    """`task_nature` → значение `Problem.character` («» = не размечено)."""
    return CHARACTER_BY_NATURE.get(task_nature or '', '')
