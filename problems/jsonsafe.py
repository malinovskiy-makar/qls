# -*- coding: utf-8 -*-
"""JSON, который безопасно положить внутрь тега `<script>`.

⚠️ ЗАЧЕМ ЭТО ЕСТЬ (сессия 3Б, фаза 2). Обычный `json.dumps` экранирует
кавычку и обратный слэш — и всё. Символы `<`, `>` и `&` он оставляет как
есть, а браузер разбирает разметку РАНЬШЕ, чем JavaScript. Поэтому строка

    </script><img src=x onerror=alert(1)>

внутри любого поля закрывает наш скрипт и открывает свой. Названия групп и
работ печатает репетитор, а уезжают они в `<script>` на экране календаря и
каталога — то есть это не теория.

Экранируются ровно три символа, теми же последовательностями, что и в
`django.utils.html.json_script`. Для JSON `\\u003C` и `<` — одно и то же
значение, поэтому клиентский `JSON.parse` получает исходную строку без
единой правки на своей стороне.

**Почему не `{{ x|json_script:"id" }}`.** Штатный фильтр Django делает то же
самое, но требует переписать и место чтения: значение переезжает в отдельный
тег, и JS обязан достать его через `document.getElementById(...).textContent`.
Здесь пять мест, и два из них разбираются проверками, которые вырезают
инлайн-скрипт из шаблона и исполняют его в node. Помощник даёт ту же защиту,
не трогая ни одной строки JavaScript.
"""
import json

# Те же замены, что у Django в `json_script`.
_SCRIPT_ESCAPES = {
    ord('<'): '\\u003C',
    ord('>'): '\\u003E',
    ord('&'): '\\u0026',
}


def dumps_for_script(value, **kwargs):
    """`json.dumps` + экранирование `<`, `>`, `&`.

    Результат разрешено выводить в шаблоне через `|safe` внутри `<script>`:
    выйти из тега им уже нельзя.
    """
    kwargs.setdefault('ensure_ascii', False)
    return json.dumps(value, **kwargs).translate(_SCRIPT_ESCAPES)
