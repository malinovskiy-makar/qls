"""Таксономия `Problem.problem_type` — ЕДИНСТВЕННАЯ точка правды проекта.

Зачем отдельный модуль. В банке одновременно живут ДВА словаря названий
типа, и это надолго:

- **старый** (`тест: один ответ`, `тест: верно/неверно`, `тест: все верные`,
  `тест: числовой ответ`) — им размечен боевой сервер и всё, что не прошло
  обогащение v2;
- **v2** (`единственный_выбор`, `верно_неверно`, `множественный_выбор`) —
  его записало обогащение 2026-09 поверх локального банка.

Пока код сравнивал `problem_type` со строками ОДНОГО словаря по месту, любая
поверхность видела ровно половину корпуса. Так и вышло: после обогащения v2
`catalog.testplay.game_of()` перестал находить хоть один тест с вариантами —
живых интерактивных виджетов в каталоге стало ноль на весь банк, — а игра
продолжала работать только потому, что у неё случайно оказалось два словаря
сразу. Поэтому сопоставление «строка типа → вид теста» лежит здесь, и все
потребители (каталог, игра, генератор домашних работ, поиск по словам)
читают именно его.

⚠️ Новое значение `problem_type` заводится ЗДЕСЬ и больше нигде. Если очередной
импорт или обогащение придумает своё название теста, добавить его надо в
`TEST_KIND_BY_TYPE` — тогда виджет, игровой пул, фильтр каталога и подбор в
домашку подхватят его одной правкой, а не четырьмя.

Не-тестовые значения банка (`задача с развёрнутым ответом`,
`несколько_подвопросов`, `не_задача`, `сопоставление`) в словаре намеренно
отсутствуют: у них нет автопроверяемого вида. `сопоставление` — отдельно:
ответ там задаётся НАБОРОМ ПАР, одиночным или множественным выбором он не
проверяется, поэтому видом теста он не считается.
"""

#: Виды теста. Ровно четыре: столько умеет и каталог, и Econ Rush.
SINGLE = 'single'      # один верный вариант
BOOLEAN = 'boolean'    # верно/неверно
MULTI = 'multi'        # отметить все верные
NUMERIC = 'numeric'    # короткий ответ строкой или числом, вариантов нет

TEST_KINDS = (SINGLE, BOOLEAN, MULTI, NUMERIC)

#: Подписи видов для экрана. Прежние подписи фильтра каталога, слово в слово.
KIND_LABELS = {
    SINGLE: 'один верный',
    BOOLEAN: 'верно/неверно',
    MULTI: 'выбор всех верных',
    NUMERIC: 'короткий ответ',
}

#: Строка `problem_type` → вид теста. Оба словаря названий равноправны.
TEST_KIND_BY_TYPE = {
    # --- старый словарь (боевой сервер, необогащённые задачи) -------------
    'тест: один ответ': SINGLE,
    'тест: верно/неверно': BOOLEAN,
    'тест: все верные': MULTI,
    'тест: числовой ответ': NUMERIC,
    # --- таксономия v2 (обогащение 2026-09) -------------------------------
    'единственный_выбор': SINGLE,
    'верно_неверно': BOOLEAN,
    'множественный_выбор': MULTI,
    # `тест: короткий ответ` — название из мастер-файла §5.5: словарь v2, но
    # с «тест: » в начале. Именно оно лежит в банке (3 815 задач на
    # 2026-09-12), а не `тест: числовой ответ` из старого словаря.
    'тест: короткий ответ': NUMERIC,
}

#: Какие из значений пришли обогащением v2. Нужно ровно одному потребителю —
#: `build_game_pool`: у v2-значений есть дополнительный гейт допуска в игру
#: (§7.3), потому что старый словарь уже проверен кросс-сигналом label/mark
#: при импорте, а v2 размечала модель. Перечислено списком, а не выведено из
#: формы строки: «тест: короткий ответ» — из словаря v2, хотя начинается так
#: же, как старые значения.
V2_TYPE_VALUES = frozenset({
    'единственный_выбор', 'верно_неверно', 'множественный_выбор',
    'тест: короткий ответ',
})

#: Все строки типа, которые считаются тестом, — для запросов `__in`.
TEST_TYPE_VALUES = tuple(TEST_KIND_BY_TYPE)

#: Вид → строки типа, которые ему соответствуют (тоже для запросов `__in`).
TYPES_BY_KIND = {
    kind: tuple(value for value, k in TEST_KIND_BY_TYPE.items() if k == kind)
    for kind in TEST_KINDS
}


def test_kind(problem_type):
    """Вид теста по строке `problem_type` или None, если это не тест.

    Регистр и обрамляющие пробелы не важны: значения в банк писали и
    импорт, и модель, единообразия в них нет.
    """
    return TEST_KIND_BY_TYPE.get((problem_type or '').strip().lower())


def is_test(problem_type):
    """Тест ли это. Признак один на весь проект — см. докстринг модуля."""
    return test_kind(problem_type) is not None


def kind_label(problem_type):
    """Подпись вида теста для экрана; пусто, если это не тест."""
    return KIND_LABELS.get(test_kind(problem_type), '')
