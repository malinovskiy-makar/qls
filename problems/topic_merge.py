# -*- coding: utf-8 -*-
"""
Таблица соответствий «посторонняя тема → каноническая» и сборка плана
перевешивания. Сессия 9, фаза 2.

ЗАЧЕМ. Фильтр каталога отдавал ровно 21 каноническую тему, а статистика
показывала 31 колонку: 21 каноническую и 10 посторонних — и данные учеников
лежали именно на посторонних. Канонические колонки стояли почти пустыми, и
экран читался как «много случайных тем».

⚠️ ГЛАВНОЕ, ЧТО ВЫЯСНИЛА РАЗВЕДКА: тема в статистике берётся НЕ из задачи, а
из СНИМКА в событии (`LearningEvent.topic` — денормализация «какая тема была
в момент решения»). Значит одного перевешивания задач мало: пока события
показывают на старую строку темы, посторонняя колонка остаётся. Поэтому
команда двигает ВСЕ ссылки на тему, а не только M2M задачи.

⚠️ ЧЕГО КОМАНДА НЕ ДЕЛАЕТ. Не трогает тексты условий и не пересчитывает
эмбеддинги: отпечаток строится по тексту задачи, а не по названию темы
(см. `problem_to_text` в CLAUDE.md). И не удаляет строку старой темы —
у `Topic` каскадные потомки (`Subtopic`, `TheoryPage`, `StudentTopicProgress`),
и удаление увело бы за собой чужие данные. Опустевшая тема просто перестаёт
попадать в выдачу.
"""
from problems.management.commands.apply_topic_mapping import (
    ADAS, CANONICAL, FIRM, FISC, GDP, GROWTH, INFL, INTRO, MONET, classify,
)

# ---------------------------------------------------------------------------
# Таблица соответствий — утверждена владельцем. Читается глазами.
# ---------------------------------------------------------------------------
# Слева — точное имя темы из базы, справа — каноническая тема.
MERGE_TABLE = (
    ('Безработица',                                        INFL),
    ('Инфляция',                                           INFL),
    ('Система национальных счетов',                        GDP),
    ('Государственный бюджет и бюджетно-налоговая политика', FISC),
    ('Денежный рынок. Кредитно-денежная политика',         MONET),
    ('Деньги и банки',                                     MONET),
    ('Экономический рост. Экономический цикл',             GROWTH),
    ('Издержки фирмы',                                     FIRM),
    # ⚠️ ПОПРАВКА К СПИСКУ ВЛАДЕЛЬЦА. Колонка, названная им «Введение в
    # экономическую теорию», в базе называется длиннее. Голая «Введение в
    # экономическую теорию» тоже существует (id 125) — она и становится новой
    # канонической, а длинный вариант сводится к ней.
    ('Введение в экономическую теорию. Модель спроса и предложения', INTRO),
)

# Темы, которым не нашлось канонического дома и которые СТАНОВЯТСЯ каноном.
# Перевешивать нечего — достаточно того, что они попали в `CANONICAL`.
NEW_CANONICAL = (INTRO, ADAS)


def table_rows():
    """Таблица соответствий как список пар. Отдельной функцией — ради теста."""
    return list(MERGE_TABLE)


def plan(topic_names_with_data):
    """План перевешивания: [(старое имя, новое имя, откуда правило)].

    `topic_names_with_data` — имена НЕканонических тем, на которых висят
    учебные события. Всё, что не покрыто таблицей, доразбирается
    существующим классификатором проекта (`apply_topic_mapping.classify`) —
    сочинять для этого второе правило нельзя, оно разъехалось бы с первым.
    Классификатор молчит — тема остаётся как есть и попадает в отчёт: лучше
    честная лишняя колонка, чем выдуманный дом.
    """
    canon = set(CANONICAL)
    rows = []
    seen = set()
    for old, new in MERGE_TABLE:
        if old in canon:            # тема уже стала канонической — не трогаем
            continue
        rows.append((old, new, 'таблица'))
        seen.add(old)

    for name in sorted(topic_names_with_data):
        if name in seen or name in canon:
            continue
        target = classify(name)
        if target is None or target == name:
            continue
        rows.append((name, target, 'классификатор'))
        seen.add(name)
    return rows


def unresolved(topic_names_with_data):
    """Темы с данными, которым дома не нашлось совсем. Их показываем владельцу."""
    canon = set(CANONICAL)
    covered = {old for old, _ in MERGE_TABLE}
    out = []
    for name in sorted(topic_names_with_data):
        if name in canon or name in covered:
            continue
        target = classify(name)
        if target is None or target == name:
            out.append(name)
    return out
