# -*- coding: utf-8 -*-
"""С14, Уровень 0 — эталонные наборы для измерителя поиска.

Здесь живут сборка наборов и их формат на диске. Django импортируется только
там, где без него никак; нормализация и группировка — чистые функции, чтобы
проверяться без базы.

## Три набора и что каждым можно утверждать

**A — дубликаты по тексту.** Мерит функцию «Похожие задачи» (задача → задача),
а НЕ поиск по описанию. Это разные вещи, и путать их нельзя.

⚠️ Набор A НЕ берётся из таблицы `DuplicateCandidate`, хотя `EMBEDDINGS.md`
предлагает именно это. Все 10 731 пары там помечены «подтверждён», но
`reviewed_by`/`reviewed_at` пусты у каждой, все созданы за шесть секунд
08.06.2026, а статус проставила `process_duplicates` автоматически по порогу
косинуса ≥ 0,95 — человек не смотрел ни одной. Мерить поиск на парах,
отобранных близостью тех же векторов, — замкнутый круг: recall выйдет около
единицы и не будет значить ничего. Поэтому пары строятся по совпадению
нормализованного текста, то есть по признаку, независимому от измеряемого.

**B — обратная генерация.** Модель читает задачу и пишет фразы, которыми её
искали бы. Правильный ответ известен заранее.

⚠️⚠️ ЖЁСТКОЕ ПРАВИЛО НАБОРА B, НАРУШАТЬ НЕЛЬЗЯ:

    По набору B РАЗРЕШЕНО утверждать «вариант Б лучше варианта А».
    По набору B ЗАПРЕЩЕНО утверждать «наш поиск даёт качество 0,85».

Синтетика систематически завышает абсолютные цифры: nDCG@10 примерно на 0,2
против человеческой разметки. При этом относительный порядок систем
сохраняется (корреляция Кендалла 0,73–0,92), поэтому сравнивать варианты
между собой — можно, называть абсолютное качество — нет.

**C — живые формулировки владельца.** Не синтетика: настоящий преподаватель,
настоящая практика, просто источник не лог, а голова. Это приёмочный набор,
и абсолютные цифры называются по нему.

## Формат файла

Один набор — один JSON. Ключи внутри `cases` выбраны так, чтобы тот же файл
без переделки пошёл на дообучение модели (уровень 5): `query`,
`relevant_ids`, `hard_negative_ids`. Трудных отрицательных мы пока не
добываем, поле лежит с `null` — чтобы за ними не пришлось платить генерацией
второй раз.
"""
from __future__ import annotations

import json
import re
import unicodedata
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

from problems.search_eval_metrics import EvalCase

# Каталог, где живут собранные наборы. Рядом с кодом, а не в reports/:
# это входные данные для команды, а не отчёт для человека.
DATA_DIR = Path(__file__).resolve().parent / 'data'

# Короче этого числа символов текст не считается опознавательным. «Найдите
# равновесную цену.» встречается в банке сотнями и одинаковой задачей её не
# делает — такие группы были бы мусором, а не эталоном.
MIN_STATEMENT_LEN = 80

_ПРОБЕЛЫ = re.compile(r'\s+')
_НЕ_БУКВЫ = re.compile(r'[^0-9a-zа-я ]+')


def normalize_statement(text) -> str:
    """Приводит условие к виду, по которому две задачи сравниваются как равные.

    Убирает регистр, разметку, знаки препинания и различия в пробелах; «ё»
    приравнивается к «е». ЧИСЛА СОХРАНЯЮТСЯ — именно они и отличают похожие
    задачи друг от друга, без них половина банка склеилась бы в одну группу.
    """
    s = unicodedata.normalize('NFKC', text or '').lower().replace('ё', 'е')
    s = _ПРОБЕЛЫ.sub(' ', s)
    s = _НЕ_БУКВЫ.sub('', s)
    return s.strip()


def group_duplicates_by_text(rows, min_len=MIN_STATEMENT_LEN) -> list[list[int]]:
    """Группирует задачи с совпадающим нормализованным текстом.

    rows — последовательность пар (id, statement). Возвращает список групп по
    два и более id, каждая отсортирована, сами группы — по первому id.
    Одиночки и слишком короткие тексты отбрасываются.
    """
    корзины = defaultdict(list)
    for pid, statement in rows:
        ключ = normalize_statement(statement)
        if len(ключ) < min_len:
            continue
        корзины[ключ].append(pid)
    группы = [sorted(ids) for ids in корзины.values() if len(ids) > 1]
    группы.sort(key=lambda g: g[0])
    return группы


def save_eval_set(path, name, description, cases, warnings=None,
                  mode='text') -> Path:
    """Пишет набор на диск. Перезаписывает файл целиком.

    mode — чем задаётся запрос:
      'text'    — строку надо закодировать моделью (наборы B и C);
      'problem' — берётся УЖЕ ПОСЧИТАННЫЙ вектор задачи из `meta`
                  ['query_problem_id'] (набор A).

    ⚠️ РЕЖИМ ЗАПИСАН В ФАЙЛЕ, А НЕ УГАДЫВАЕТСЯ ПО СОДЕРЖИМОМУ. Набор A мерит
    функцию «Похожие задачи», и прод считает её вектор-к-вектору
    (`cache_similar`), а не кодированием текста. Перепутав режимы, мы честно
    посчитаем метрику — но не той функции, которой думаем.
    """
    if mode not in ('text', 'problem'):
        raise ValueError(f'Неизвестный режим набора: {mode!r}. '
                         'Допустимы «text» и «problem».')
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    данные = {
        'name': name,
        'description': description,
        'mode': mode,
        'built_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
        'count': len(cases),
        'warnings': list(warnings or []),
        'cases': [
            {
                'query': c.query,
                'relevant_ids': sorted(c.relevant_ids),
                'hard_negative_ids': None,
                'meta': c.meta,
            }
            for c in cases
        ],
    }
    path.write_text(
        json.dumps(данные, ensure_ascii=False, indent=1), encoding='utf-8')
    return path


def load_eval_set(path):
    """Читает набор с диска. Возвращает (мета, список EvalCase)."""
    данные = json.loads(Path(path).read_text(encoding='utf-8'))
    случаи = [
        EvalCase(
            query=c['query'],
            relevant_ids=c['relevant_ids'],
            meta=c.get('meta') or {},
        )
        for c in данные['cases']
    ]
    мета = {k: v for k, v in данные.items() if k != 'cases'}
    return мета, случаи
