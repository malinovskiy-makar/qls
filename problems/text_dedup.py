"""Сопоставление текстов задач — поиск копий внутри банка.

Отдельно от `text_clean.py`: тот приводит текст в порядок ПРИ ПОКАЗЕ, а
здесь текст только СРАВНИВАЕТСЯ, в базу нормализованный вид не попадает
никогда. Общее у модулей одно — регулярка чисел, и она берётся отсюда
импортом, а не переписывается.

Зачем модуль. У 2 426 задач банка олимпиада, год и этап известны точно:
ссылка на первоисточник совпала буквально (`OlympiadRef`, методы
`url_exact` и `url_www_normalized`). Те же самые задачи лежат в банке ещё
раз — вставленные из МатЭк, Школково, Overleaf-архивов, иногда вообще без
указания источника. Команда `find_olympiad_text_duplicates` находит их по
тексту и переносит метаданные олимпиады на копию.

⚠️ ЧИСЛА — ЭТО ПРИГОВОР, А ТЕКСТ ТОЛЬКО ПОДОЗРЕНИЕ. Два условия с
одинаковой структурой фразы, но разными исходными данными («$P = 100 - Q$»
против «$P = 90 - 2Q$») — это РАЗНАЯ задача с другим ответом, а не копия,
даже при сходстве текста 98 %. Поэтому `numeric_tokens_match` стоит ПЕРЕД
дорогим fuzzy-сравнением и не имеет допусков: мультимножество чисел либо
совпало целиком, либо пара отбрасывается.

⚠️ ЧИСЛА ВЫНИМАЮТСЯ ИЗ СЫРОГО ТЕКСТА, НЕ ИЗ НОРМАЛИЗОВАННОГО. Не
микрооптимизация: `normalize_for_compare` применяет NFKC, а тот переписывает
надстрочные цифры («Q²» → «Q2») и дроби («½» → «1⁄2»). Числовой гейт —
последний рубеж перед записью в базу, и он обязан смотреть на то, что
действительно написано в условии, а не на то, во что это превратила
подготовка к сравнению.
"""
import hashlib
import re
import unicodedata
from collections import Counter
from decimal import Decimal, InvalidOperation

# Регулярки чисел — ИЗ text_clean, не свои. Там они уже ловят число целиком
# со знаком и дробной частью (иначе «−1,22» распадётся на «1» и «22») и
# понимают латеховскую запись десятичной запятой «0{,}5».
from problems.text_clean import _LATEX_COMMA, _NUMBER

# Все виды тире и минусов, которыми источники пишут одно и то же.
_DASHES = re.compile('[‐‑‒–—―−]')
# Пробельные символы, которые не ловит \s: неразрывный и узкий неразрывный.
_HARD_SPACES = str.maketrans({' ': ' ', ' ': ' ', ' ': ' '})
_WHITESPACE = re.compile(r'\s+')


def _canonical_number(token: str) -> str:
    """Одно число — одна строка, как бы его ни записали.

    «100», «100,0» и «100.00» — одно и то же число; «100» и «90» — разные.
    Знак сохраняется: подмена знака уже стоила проекту чистки 4 930 задач
    (см. модульный docstring `text_clean`).
    """
    cleaned = token.replace('−', '-').replace(',', '.').lstrip('+')
    try:
        value = Decimal(cleaned).normalize()
    except InvalidOperation:  # на всякий случай; регулярка сюда мусор не пустит
        return cleaned
    if value == 0:
        return '0'  # иначе «-0» и «0» разошлись бы
    return format(value, 'f')


def extract_numeric_tokens(text) -> Counter:
    """Все числа текста как МУЛЬТИМНОЖЕСТВО нормализованных строк.

    Мультимножество, а не множество: «фирма A и фирма B выпускают по 10»
    и «фирма выпускает 10» — разные условия, и число повторов это ловит.

    Порядок не важен — важен состав. Переставленные местами «P = 100 - 2Q,
    Q = 30» и «Q = 30, P = 100 - 2Q» описывают одну и ту же задачу.
    """
    return Counter(
        _canonical_number(t)
        for t in _NUMBER.findall(_LATEX_COMMA.sub(',', text or ''))
    )


def numeric_tokens_match(a: Counter, b: Counter) -> bool:
    """Точное совпадение мультимножества. Никаких «почти совпадает»."""
    return a == b


def normalize_for_compare(text) -> str:
    """Текст для СРАВНЕНИЯ: регистр, пробелы и вид тире перестают различать.

    Только обратимые по смыслу приведения — ничего не выбрасывается и
    ничего не дописывается. Пунктуация и формулы остаются как есть: в
    олимпиадном условии «$Q^2$» и «$Q$» — разные задачи.

    В базу результат НЕ пишется никогда, это ключ сравнения и только.
    """
    text = unicodedata.normalize('NFKC', text or '')
    text = text.translate(_HARD_SPACES)
    text = _DASHES.sub('-', text)
    return _WHITESPACE.sub(' ', text).strip().lower()


def text_fingerprint(text) -> str:
    """SHA-1 нормализованного текста — ключ группировки точных совпадений."""
    return hashlib.sha1(
        (text or '').encode('utf-8'), usedforsecurity=False).hexdigest()


def problem_identity_text(problem) -> str:
    """Что считаем «текстом задачи»: условие ПЛЮС подпункты.

    ⚠️ ПОДПУНКТЫ ОБЯЗАТЕЛЬНЫ, И ЭТО ЗАМЕРЕНО. У тестов условие часто
    сводится к общей шапке, а содержание живёт в подпунктах: 30 задач
    банка имеют побайтово одинаковое «Три из четырёх предлагаемых
    вариантов имеют некоторое общее свойство…» и 30 РАЗНЫХ наборов
    подпунктов. Без подпунктов это 30 ложных привязок из одной группы.
    По всему банку включение подпунктов убирает 702 ложные группы
    совпадения (3 279 → 2 577).

    Решение и ответ в отпечаток НЕ входят: у копии их может не быть вовсе,
    а задача от этого другой не становится.

    ⚠️ Требует `prefetch_related('parts')` при батч-запросе, иначе N+1.
    """
    chunks = [problem.statement or '']
    chunks.extend(part.statement or '' for part in problem.parts.all())
    return ' \n '.join(chunks)


def fuzzy_ratio(a: str, b: str) -> float:
    """Текстовое сходство как доля 0..1 (rapidfuzz отдаёт 0..100).

    ⚠️ ИМЕННО `fuzz.ratio`, А НЕ `token_sort_ratio`, И ЭТО НЕ ВСЁ РАВНО.
    `token_sort_ratio` сортирует слова перед сравнением, то есть выбрасывает
    порядок. Настоящая копия порядок слов сохраняет — расходятся копии
    вставками и выпадениями (маркер источника, склеенный перенос), а это
    `ratio` и меряет. Зато словарь олимпиадной экономики беден и повторяем
    («спрос», «предложение», «фирма», «равновесие»), и сортировка слов
    надувала бы сходство РАЗНЫХ задач — потеря точности, которую эта
    задача позволить себе не может.

    Импорт ленивый, внутри функции: rapidfuzz живёт в `requirements/dev.in`
    и в боевой образ не едет — так же, как sentence_transformers в
    `build_embeddings`.
    """
    from rapidfuzz import fuzz
    return fuzz.ratio(a, b) / 100.0
