"""Исходы оценки ПОЧИНКИ — единственная точка правды.

Это отдельный словарь от `problems/review_categories.py`, и путать их нельзя:

  * `REVIEW_CATEGORIES` отвечает на вопрос «что не так с ЗАДАЧЕЙ»;
  * `REPAIR_OUTCOMES` отвечает на вопрос «что получилось у ПОЧИНКИ».

Смешав их в одном списке, мы потеряли бы счёт: задача может остаться сломанной
и потому, что модель её не тронула, и потому, что модель её доломала — для
плана волны 2 это разные исходы, а категория дефекта у них одна и та же.

⚠️ На экране разбора починки категорий дефекта НЕТ среди кнопок: они уже
проставлены на первом проходе и показываются справкой. Кнопок ровно пять.

СВЯЗЬ С БАЗОЙ. Импорт превращает исход в строки `ReviewVerdict` пакета
`repair_aa_20260728`, который стоит в `human_review_mark.SUPERSEDES` над
`aa_20260728`. Поэтому «починил, идеально» ОТМЕНЯЕТ прежний вердикт «брак» и
задача уходит в `approved`; остальные исходы оставляют её в браке.

⚠️ Сам исход в базе НЕ хранится (это потребовало бы миграции ради поля, чей
единственный потребитель — план второй волны). В базу уезжает то, от чего
зависит публикация: набор категорий. Правда об исходах живёт в файле
вердиктов, и он же — вход волны 2. Так записано в reports/repair_wave1/FORMAT.md.
"""

# verdict: что уедет в ReviewVerdict.category.
#   'perfect'      — фиксированная категория;
#   'origin'       — категории первого прохода (лежат в самом файле вердиктов,
#                    поэтому импорт не зависит от того, что сейчас в базе);
#   'fixed_wrong'  — фиксированная категория «правка тронула не тот дефект»;
#   None           — вердикт не пишется вовсе (задача отложена, о ней ничего
#                    не известно, и молчание честнее выдуманной оценки).
REPAIR_OUTCOMES = [
    {'key': 'fixed_perfect', 'hotkey': '1', 'verdict': 'perfect',
     'label': 'Починил, идеально',
     'hint': 'задача годится, отправляем на сайт'},
    {'key': 'fixed_partial', 'hotkey': '2', 'verdict': 'origin',
     'label': 'Починил, но не до конца',
     'hint': 'стало лучше, дефект остался'},
    {'key': 'not_fixed', 'hotkey': '3', 'verdict': 'origin',
     'label': 'Не починил вообще',
     'hint': 'ничего по сути не изменилось'},
    {'key': 'broke', 'hotkey': '4', 'verdict': 'fixed_wrong',
     'label': 'Сломал что-то',
     'hint': 'стало хуже, чем было'},
    {'key': 'later', 'hotkey': '5', 'verdict': None,
     'label': 'Скрыть задачу на потом',
     'hint': 'разбираться сейчас не хочу'},
]

OUTCOME_KEYS = [o['key'] for o in REPAIR_OUTCOMES]
OUTCOME_LABELS = {o['key']: o['label'] for o in REPAIR_OUTCOMES}
OUTCOME_VERDICT = {o['key']: o['verdict'] for o in REPAIR_OUTCOMES}
# Исход, после которого задачу можно публиковать.
PUBLISHABLE = [o['key'] for o in REPAIR_OUTCOMES if o['verdict'] == 'perfect']

# Формат файла оценок починки. Семейство то же, что у qls-review-verdicts:
# импорт принимает его той же командой, у записи те же поля problem_id /
# comment / quotes / at, добавлены `outcome` и `origin_categories`.
REPAIR_VERDICTS_FORMAT = 'qls-repair-verdicts-v1'


def categories_for(outcome, origin_categories):
    """Категории вердикта по исходу оценки. Пустой список — не писать вовсе."""
    rule = OUTCOME_VERDICT.get(outcome)
    if rule is None:
        return []
    if rule == 'origin':
        # Дефект остался — он и записывается. Если первый проход почему-то не
        # оставил категорий, честнее сказать «прочее», чем промолчать: молчание
        # означало бы «вердикта нет» и вернуло бы задачу к старому «брак» без
        # следа второго прохода.
        return sorted(origin_categories) or ['other']
    return [rule]
