import hashlib
import re

# ── Числовой гейт ───────────────────────────────────────────────────────
#
# Зачем. Главный риск дедупа по косинусу — склеить две ЗАДАЧИ ОДНОГО СЮЖЕТА
# С РАЗНЫМИ ЧИСЛАМИ. Сюжет («фирма на монопольном рынке, найдите выпуск»)
# кодируется почти одинаково, а параметры спроса разные — и это две разные
# задачи, а не дубль. Множество чисел в условии — самый дешёвый признак,
# который такую пару разводит.
#
# Эвристика намеренно грубая: она НЕ решает, дубль это или нет. Она только
# раскладывает пары на «числа совпали / совпали частично / разошлись».

# Число: необязательный знак, дробная часть через запятую или точку.
#
# ⚠️ Две ветки, и порядок важен. Первая — группы тысяч через пробел
# («1 000 000»), и она требует РОВНО ТРИ цифры после каждого пробела.
# Без этого требования «цена 10 20» склеивалась бы в одно число 1020 —
# ровно это поймал тест `test_половина`. Вторая ветка — обычное число.
# Остаётся неснимаемая двусмысленность: «100 200» — это либо сто тысяч
# двести, либо два числа подряд; берём первое, как в банке чаще.
_NUMBER_RE = re.compile(
    r'-?\d{1,3}(?:[   ]\d{3})+(?:[.,]\d+)?'
    r'|-?\d+(?:[.,]\d+)?'
)

# Служебные куски LaTeX, где цифры не параметры задачи, а разметка:
# \frac12 не даёт чисел 1 и 2 как данных, \hline{3} — тем более.
_LATEX_NOISE_RE = re.compile(
    r'\\(?:begin|end|cline|multicolumn|multirow|includegraphics|ref|label|'
    r'vspace|hspace|scalebox|resizebox|arraystretch|textwidth|linewidth)'
    r'\s*(?:\{[^{}]*\}|\[[^\]]*\])*'
)


def extract_numbers(text):
    """Множество чисел из текста условия в нормальном виде.

    Нормализация: пробелы-разделители тысяч убираются, запятая становится
    точкой, хвостовые нули дробной части отбрасываются — чтобы «12,50»
    и «12.5» считались одним числом, а «1 000» и «1000» не расходились.
    """
    if not text:
        return set()
    cleaned = _LATEX_NOISE_RE.sub(' ', text)
    out = set()
    for raw in _NUMBER_RE.findall(cleaned):
        token = re.sub(r'[\s  ]', '', raw).replace(',', '.')
        token = token.rstrip('.')
        if not token or token in ('-',):
            continue
        try:
            value = float(token)
        except ValueError:
            continue
        # Целое печатаем без дробной части: 12.0 и 12 — одно число.
        out.add(str(int(value)) if value == int(value) else str(value))
    return out


def compare_numbers(text_a, text_b):
    """Вердикт по паре: как соотносятся множества чисел двух условий."""
    a = extract_numbers(text_a)
    b = extract_numbers(text_b)
    if not a and not b:
        return 'оба без чисел'
    if not a or not b:
        return 'числа только у одной'
    if a == b:
        return 'совпадают'
    if a & b:
        return 'частично'
    return 'не совпадают'


def numbers_jaccard(text_a, text_b):
    """Доля общих чисел — для сортировки подозрительных пар."""
    a = extract_numbers(text_a)
    b = extract_numbers(text_b)
    if not a and not b:
        return 1.0
    union = a | b
    return len(a & b) / len(union) if union else 1.0


# ── Текстовый гейт ──────────────────────────────────────────────────────
#
# Косинус считается по ОТПЕЧАТКУ (формула), а дубль — это совпадение
# ПОЛНОГО текста. Символьная близость (Жаккар по 3-граммам) ничего не знает
# ни про одну формулу и потому служит независимой проверкой.

_WS_RE = re.compile(r'\s+')

#: Бюджет условия у формулы v1 — ровно столько символов она и видит.
#: Две РАЗНЫЕ длинные задачи с общей шапкой длиннее этого получают высокий
#: косинус, и текстовый гейт — единственное, что их разводит.
V1_STATEMENT_BUDGET = 500


def normalize(text):
    return _WS_RE.sub(' ', (text or '').lower()).strip()


def trigrams(text):
    t = normalize(text)
    return {t[i:i + 3] for i in range(max(len(t) - 2, 0))} or {t}


def text_jaccard(a, b):
    """Символьная близость двух множеств 3-грамм."""
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def header_clash(text_a, text_b):
    """Пара «общая шапка»: первые 500 символов совпали, полные тексты — нет."""
    na, nb = normalize(text_a), normalize(text_b)
    return na[:V1_STATEMENT_BUDGET] == nb[:V1_STATEMENT_BUDGET] and na != nb


# ── Гейт по подпунктам (для content_hash) ───────────────────────────────
#
# `content_hash` — MD5 одного поля `statement`. Подпунктов он не видит, и
# самая большая «группа точного совпадения» в банке — 30 РАЗНЫХ тестовых
# заданий с общей шапкой, различающихся вариантами в `ProblemPart`.


def _norm_part(text):
    return _WS_RE.sub(' ', (text or '')).strip()


def parts_fingerprint(parts):
    """Отпечаток подпунктов: условие и ответ каждого, по порядку.

    ⚠️ Метка пункта («а», «б») в отпечаток НЕ входит: метки не уникальны и
    у разных источников расставлены по-разному, а различать задачи должно
    содержимое.
    """
    куски = ['%s|%s' % (_norm_part(st), _norm_part(ans)) for st, ans in parts]
    return hashlib.md5(' '.join(куски).encode('utf-8'),
                       usedforsecurity=False).hexdigest()


def parts_key(parts):
    """Ключ гейта: число подпунктов И их отпечаток."""
    parts = list(parts)
    return (len(parts), parts_fingerprint(parts))
