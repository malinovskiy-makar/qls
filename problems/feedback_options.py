# Адрес → ключ экрана. ПОРЯДОК ВАЖЕН: более длинный путь проверяется раньше,
# иначе «/catalog/problem/» совпал бы с «/catalog/».
PAGE_KEY_RULES = (
    ('/calc2/', 'calc2'),
    ('/catalog/problem/', 'problem'),
    ('/catalog/map/', 'map'),
    ('/catalog/', 'catalog'),
    ('/game/', 'game'),
    ('/olympiads/', 'olympiads'),
    ('/student/', 'lessons'),
    ('/teacher/', 'teacher'),
    ('/profile/stats/', 'stats'),
    ('/profile/', 'profile'),
    ('/login/', 'auth'),
    ('/register/', 'auth'),
    ('/calendar/', 'calendar'),
    ('/textbook/', 'textbook'),
)

ALL_PAGE_KEYS = (
    set(FEEDBACK_OPTIONS)
    | set(FEEDBACK_ALIASES)
    | {key for _, key in PAGE_KEY_RULES}
)


def page_key_for(path):
    """Ключ экрана по адресу. Главная — `home`, незнакомое — `other`."""
    path = path or '/'
    for prefix, key in PAGE_KEY_RULES:
        if path.startswith(prefix):
            return key
    if path == '/':
        return 'home'
    return 'other'


def options_for(page_key):
    """Список вариантов для экрана. Незнакомый ключ → общий список."""
    key = FEEDBACK_ALIASES.get(page_key, page_key)
    return FEEDBACK_OPTIONS.get(key, FEEDBACK_OPTIONS['other'])
