ALL_PAGE_KEYS = (
    set(FEEDBACK_OPTIONS)
    | set(FEEDBACK_ALIASES)
    | {key for _, key in PAGE_KEY_RULES}
)


def page_key_for(path):
    """Ключ экрана по адресу. Главная — `home`, незнакомое — `other`."""
    path = path or '/'
    for prefix, key in PAGE_KEY_RULES:
        if path.startswith(prefix):
            return key
    if path == '/':
        return 'home'
    return 'other'


