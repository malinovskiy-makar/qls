# -*- coding: utf-8 -*-
"""Балл на экране — ЕДИНСТВЕННАЯ точка форматирования.

⚠️ ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Одно и то же число печаталось двумя способами, и
на соседних экранах выходили разные записи одной оценки:

* сводка решений (`teacher/views_groups._clean_points`) отдавала **строку**
  «4.25» — строку Django не локализует, и на экране стояла ТОЧКА;
* разбор работы (`problems/work_review._clean`) отдавал **Decimal** «4.25» —
  Decimal локализуется, и на экране стояла ЗАПЯТАЯ.

Тот же разнобой давал лишний нуль: `Decimal('0.50')` печатался как «0,50»
(`normalize()` в старом помощнике применялся только к целым), а
`floatformat:"-2"` по своему устройству печатает ДВА знака, как только у
числа есть дробная часть, — то есть тоже «0,50».

Правила записи (решение владельца, ревью 15.08, п. 1.4):
    разделитель — запятая; незначащие нули отбрасываются.
    0.5 → «0,5»;  2.0 → «2»;  4.25 → «4,25»;  None → «».

Функция-близнец `models_platform.difficulty_label` устроена так же и по той
же причине.
"""
from decimal import Decimal, InvalidOperation

# Сколько знаков после запятой имеет смысл у балла. Дробные баллы берутся из
# двух мест: половина максимума в пресетах и вес пункта в задаче (доли вроде
# 1,25 из пяти). Дальше второго знака чисел не бывает, а округление до него
# закрывает 3,3333… от деления балла на три пункта.
PLACES = Decimal('0.01')


def ball(value, default=''):
    """Балл строкой по-русски: «0,5», «2», «4,25». Пусто → `default`.

    Принимает что угодно числовое: int, float, Decimal, строку с точкой или
    с запятой. Нечисловое возвращает `default` — печатать «None» на экране
    хуже, чем не печатать ничего.
    """
    if value is None or value == '':
        return default
    if isinstance(value, str):
        value = value.strip().replace(',', '.')
    try:
        number = Decimal(str(value)).quantize(PLACES)
    except (InvalidOperation, ValueError, TypeError):
        return default
    text = '%s' % number
    if '.' in text:
        text = text.rstrip('0').rstrip('.')
    if text in ('-0', ''):          # «-0,00» бывает от вычитания, «-0» — нет
        text = '0'
    return text.replace('.', ',')


def ball_dot(value, default=''):
    """То же число, но С ТОЧКОЙ — для машинных мест, не для экрана.

    ⚠️ Нужна там, где значение читает НЕ человек, а код: атрибут `data-*`,
    который разбирает `parseFloat`, и `value` у поля `type="number"`. Обе
    записи с запятой там молча ломаются — `parseFloat('1,50')` даёт 1, а
    числовое поле стирает собственное начальное значение.
    """
    return ball(value, default).replace(',', '.')


def pair(value, maximum, default='—'):
    """«4,25 из 18». Обе половины — одной записью, чтобы не разъехались."""
    left = ball(value)
    if not left:
        return default
    right = ball(maximum)
    return '%s из %s' % (left, right) if right else left
