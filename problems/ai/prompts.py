def system_blocks(profile):
    """Системная часть запроса: [неизменное ядро, профиль].

    Возвращает именно СПИСОК блоков, а не склеенную строку: кэшируется
    только первый, и граница между «неизменным» и «может меняться» должна
    быть видна в коде, а не подразумеваться.
    """
    if profile not in PROFILES:
        raise KeyError('Неизвестный профиль запроса: %s' % profile)
    return [CORE, PROFILES[profile]]
