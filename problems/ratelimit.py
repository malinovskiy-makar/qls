# -*- coding: utf-8 -*-
"""Ограничение частоты попыток — общий счётчик на весь проект.

⚠️ **ЗАЧЕМ.** Django из коробки НЕ защищает от подбора пароля: форма входа
принимает попытки бесконечно и с любой скоростью. Пока живых пользователей
нет, это теория; к бете с живыми репетиторами — уже нет.

**Ключ комбинированный, и это главное решение здесь.** Считать только по
имени пользователя — значит впустить перебор с созданием новых имён и,
хуже того, дать любому желающему запереть чужой аккаунт: назвал чужой логин
десять раз, и человек не войдёт. Считать только по адресу в сети — значит
наказать целую школу за общий выход в интернет: один ученик ошибся, не
входит никто. Поэтому счётчиков ДВА, и запрет наступает по любому из них,
а лимит у адреса заметно выше.

**Задержка нарастающая, а не «отлуп на час».** Первые промахи бывают у
живого человека: раскладка, Caps Lock, старый пароль. Ступени подобраны так,
чтобы человек ничего не заметил, а перебор упёрся: 5 промахов — 30 секунд,
дальше 2 минуты, 10 минут, полчаса.

**Счётчики лежат в кэше Django.** Сегодня это память процесса
(`LocMemCache`), и у этого есть два следствия, которые надо знать честно:
счётчик не переживает перезапуск, и при нескольких воркерах у каждого он
свой. Для одного процесса на бесплатном хостинге это работает; переезд на
Redis — смена `CACHES` в настройках, **ни одной строки здесь менять не
придётся**: модуль знает только `django.core.cache.cache`.
"""
import time

from django.core.cache import cache

# ── Ступени запрета: (число промахов, на сколько секунд закрыть) ─────────
#
# Читается сверху вниз, берётся последняя подошедшая ступень.
LADDER = (
    (5, 30),        # пять промахов — полминуты
    (8, 120),       # восемь — две минуты
    (12, 600),      # двенадцать — десять минут
    (20, 1800),     # двадцать — полчаса
)

# Сколько живёт счётчик промахов без новых попыток. Сутки: иначе медленный
# перебор («по три попытки в час») не накопит ни одной ступени.
WINDOW = 24 * 60 * 60

# Насколько мягче лимит для адреса в сети, чем для имени пользователя.
# За одним адресом может сидеть класс из тридцати человек.
IP_MULTIPLIER = 6


def _key(scope, ident, suffix):
    """Ключ кэша. `ident` приводим к нижнему регистру и режем по длине.

    Длина важна: имя пользователя приходит от клиента, а в ключ memcached
    нельзя класть что угодно любой длины.
    """
    safe = str(ident).strip().lower()[:100]
    return 'rl:%s:%s:%s' % (scope, suffix, safe)


def _ladder_for(count, multiplier=1):
    """Сколько секунд запрета положено при таком числе промахов."""
    seconds = 0
    for threshold, penalty in LADDER:
        if count >= threshold * multiplier:
            seconds = penalty
    return seconds


def client_ip(request):
    """Адрес клиента. За обратным прокси берём ПЕРВЫЙ из X-Forwarded-For.

    ⚠️ Заголовок подделывается кем угодно, поэтому он не доказательство
    личности. Здесь он и не нужен как доказательство: цель — развести
    попытки разных людей, а не установить, кто они. Хостинг за обратным
    прокси свой заголовок переписывает, и первым в списке стоит настоящий
    клиент.
    """
    forwarded = request.META.get('HTTP_X_FORWARDED_FOR', '')
    if forwarded:
        return forwarded.split(',')[0].strip()[:64]
    return (request.META.get('REMOTE_ADDR') or '')[:64]


def note_failure(scope, ident, multiplier=1):
    """Записать неудачную попытку. Возвращает новое число промахов."""
    key = _key(scope, ident, 'n')
    count = (cache.get(key) or 0) + 1
    cache.set(key, count, WINDOW)
    penalty = _ladder_for(count, multiplier)
    if penalty:
        cache.set(_key(scope, ident, 'until'), time.time() + penalty, penalty)
    return count


def clear(scope, ident):
    """Сбросить счётчик — после успешного входа."""
    cache.delete_many([_key(scope, ident, 'n'), _key(scope, ident, 'until')])


def seconds_locked(scope, ident):
    """Сколько секунд осталось ждать. Ноль — можно пробовать."""
    until = cache.get(_key(scope, ident, 'until'))
    if not until:
        return 0
    left = int(until - time.time())
    return left if left > 0 else 0


def failures(scope, ident):
    """Текущее число промахов — для тестов и диагностики."""
    return cache.get(_key(scope, ident, 'n')) or 0


# ── Готовая пара «имя + адрес» для форм входа и восстановления ───────────

def check(scope, request, ident):
    """Можно ли пробовать. Возвращает секунды ожидания (0 — можно).

    Проверяются ОБА счётчика; запрет наступает по большему из них.
    """
    by_ident = seconds_locked(scope, ident) if ident else 0
    by_ip = seconds_locked(scope + ':ip', client_ip(request))
    return max(by_ident, by_ip)


def register_failure(scope, request, ident):
    """Промах: двигаем оба счётчика."""
    if ident:
        note_failure(scope, ident)
    note_failure(scope + ':ip', client_ip(request), multiplier=IP_MULTIPLIER)


def register_success(scope, request, ident):
    """Успех: гасим счётчик имени.

    ⚠️ Счётчик АДРЕСА намеренно НЕ гасим. Иначе перебор обнулял бы его
    каждым удачным входом в собственный аккаунт нападающего — то есть
    ограничение по адресу снималось бы тем, кого оно и должно ловить.
    """
    if ident:
        clear(scope, ident)
