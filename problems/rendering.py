# -*- coding: utf-8 -*-
"""Рендерер условий задач для ``content_format='markdown'``.

Подготовка к конвертации корпуса (CORPUS-FORMAT.md §2б). Функция
``render_markdown`` — единственная точка входа: текст на входе, безопасный
HTML-фрагмент на выходе. Ничего не пишет в базу, ничего не читает из базы.

⚠️ Легаси (``content_format='plain'``, все 31 694 сегодняшних задачи) через
этот модуль НЕ проходит вообще — шаблон выбирает ветку по полю, см.
``catalog/templates/catalog/problem_detail.html``.

## Почему это вообще осторожно писать

``docs/SECURITY.md`` называет единственную дыру уровня «высокая» за весь
аудит проекта ровно в этом месте — вывод текста задачи. Правило проекта до
сих пор было «экранируем всегда, HTML не разрешаем вообще». Рендерер это
правило меняет впервые, поэтому:

* markdown-парсер настроен на УЗКОЕ подмножество (жирный, курсив, списки,
  простые таблицы, переносы), а не полный CommonMark — не потому что лень,
  а потому что каждое включённое правило — это новая поверхность;
* HTML в самой разметке не разрешён (``html: False`` у markdown-it) — сырой
  ``<script>`` в источнике превращается в текст ДО того, как дойдёт до
  санитайзера;
* после markdown — второй, независимый рубеж: ``nh3`` (Rust-биндинг
  Ammonia) с allow-list. Ни один тег/атрибут вне списка не выживает, даже
  если бы markdown-it что-то пропустил.

## Математика — почему нужен отдельный проход ДО markdown

LaTeX-формулы состоят из `_` (нижние индексы: ``$x_1$``) и могут содержать
`*`. Обычный markdown-парсер не знает про ``$...$`` как границу — без
защиты ``$x_1$`` превратится в ``$x<em>1</em>$`` до того, как формула
доедет до KaTeX. Поэтому математика вырезается плейсхолдерами ДО
markdown-обработки и возвращается на место НЕТРОНУТОЙ после.

Логика поиска границ (``_math_span_end``/``_find_close``) — БУКВАЛЬНОЕ
зеркало ``templates/_katex_dollars.html`` (``mathSpanEnd``/``findClose``):
тот же порядок пар (``$$`` раньше ``$$``... то есть ``$$`` раньше ``$``),
то же правило «``\\$`` внутри формулы не разделитель, а законный символ»
и то же правило «``\\\\`` — пара, и ``$`` после неё разделитель».
Если эти реализации разойдутся, на странице разойдётся то, что
показал рендерер, и то, что подсветил авторендер KaTeX — расхождение
не поймает ни один тест на стороне Python, поэтому оно прокомментировано
здесь явно: меняешь одно — меняй и остальные.

⚠️ Зеркал ЧЕТЫРЕ, а не два, и это выяснилось дорогой ценой — правку
``\\\\$`` пришлось вносить четырежды:

1. ``_find_close`` здесь — то, что рисует страницу;
2. ``findClose`` в ``templates/_katex_dollars.html`` — то, что видит
   авторендер KaTeX в браузере;
3. ``findClose`` в ``corpus_converter/katex_preflight._MEASURE_JS`` —
   то, чем меряют шлюз (иначе замер перестаёт быть замером боевого
   показа);
4. ``_find_close`` в ``corpus_converter/tex_lexer.py`` — то, чем
   конвертер решает, где кончается формула. Ошибка здесь дороже всех:
   непарные ``$`` лексер объявляет валютой, ``math_canon`` экранирует
   их, и формула деградирует в прозу ещё до показа.

``\\$`` ВНЕ формулы — не математика, а экранированная валюта (домашняя
конвенция корпуса, тот же файл). Она тоже защищается плейсхолдером —
иначе CommonMark интерпретирует обратный слэш как экранирование пунктуации
и молча его съест (``\\$`` → ``$``), а клиентский скрипт
(``fixCurrencyDollars``) ждёт на странице именно ``\\$``, чтобы снять
экранирование сам, при показе.
"""
from __future__ import annotations

import re

import nh3
from django.utils.html import escape
from markdown_it import MarkdownIt

# ---------------------------------------------------------------------------
# Защита математики и экранированной валюты
# ---------------------------------------------------------------------------

#: Плейсхолдер — символы из зоны личного пользования Юникода (Private Use
#: Area), той же идеи, что и  в _katex_dollars.html: обычный текст
#: их не содержит, markdown-it не приписывает им никакого синтаксиса
#: (не пунктуация, не управляющий символ), поэтому индекс внутри выживает
#: через любое количество вложенных **жирный*курсив** конструкций.
_PLACEHOLDER_OPEN = ''
_PLACEHOLDER_CLOSE = ''
_PLACEHOLDER_RE = re.compile(_PLACEHOLDER_OPEN + r'(\d+)' + _PLACEHOLDER_CLOSE)

#: Пары разделителей математики. Порядок обязателен: `$$` раньше `$`,
#: иначе `$$x$$` читается как два пустых `$$`-разделителя одинарного `$`.
#: Тот же порядок — в _katex_dollars.html (mathSpanEnd) и в auto-render
#: KaTeX (см. catalog/CLAUDE.md: «$$ раньше $»).
_MATH_PAIRS = (('$$', '$$'), ('\\[', '\\]'), ('\\(', '\\)'), ('$', '$'))


def _find_close(s, start, close):
    """Найти индекс закрывающего разделителя, пропуская ``\\$`` внутри.

    Зеркало ``findClose`` из _katex_dollars.html. ``\\$`` внутри формулы —
    законная запись доллара (её рисует сам KaTeX), не граница формулы —
    поэтому поиск закрытия его не замечает вовсе, независимо от того,
    что мы ищем (`$`, `$$`, `\\)` или `\\]`).

    ⚠️ Пропускается также пара ``\\\\`` (перенос строки), и это не
    украшение. Без неё в ``\\\\$`` первый слеш проходил как обычный
    символ, а ВТОРОЙ вместе с ``$`` читался как «экранированный доллар»,
    и формула не закрывалась вовсе — она съедала текст до следующего
    ``$``, а KaTeX отвечал ``Can't use function '$' in math mode``.
    Замер по всей базе: расхождение ровно у 25 задач, все — три новых
    источника (живые #62556, #62939), легаси не задет ни одной.

    Пропускаются ИМЕННО ``\\\\`` и ``\\$``, а не «слеш и любой следующий
    символ»: последнее съело бы сам разделитель ``\\)`` / ``\\]`` и
    сломало бы формулы в скобочной записи.
    """
    i, n, close_len = start, len(s), len(close)
    while i < n:
        if s[i] == '\\' and i + 1 < n and s[i + 1] in ('\\', '$'):
            i += 2
            continue
        if s[i:i + close_len] == close:
            return i
        i += 1
    return -1


def _math_span_end(s, i):
    """Если с позиции ``i`` начинается формула — индекс сразу за её концом.

    Иначе — ``i`` без изменений (зеркало ``mathSpanEnd``). Незакрытый
    разделитель формулой не считается: одиночный ``$5`` без пары остаётся
    обычным текстом, как и в текущем plain-режиме.
    """
    for open_, close in _MATH_PAIRS:
        if s[i:i + len(open_)] != open_:
            continue
        end = _find_close(s, i + len(open_), close)
        if end == -1:
            continue
        return end + len(close)
    return i


def _protect_math_and_currency(text):
    """Вырезать математику и `\\$`-валюту плейсхолдерами.

    Возвращает (текст_с_плейсхолдерами, [защищённые_куски]). Порядок
    проверки на каждой позиции — как в maskOutsideMath: сначала `\\$`
    (валюта), потом граница формулы. Так `\\$100` никогда не пытается
    открыть формулу собой, даже если после него встретится непарный `$`.
    """
    protected = []
    out = []
    i, n = 0, len(text)
    while i < n:
        if text[i] == '\\' and i + 1 < n and text[i + 1] == '$':
            idx = len(protected)
            protected.append('\\$')
            out.append(_PLACEHOLDER_OPEN + str(idx) + _PLACEHOLDER_CLOSE)
            i += 2
            continue
        end = _math_span_end(text, i)
        if end > i:
            idx = len(protected)
            protected.append(text[i:end])
            out.append(_PLACEHOLDER_OPEN + str(idx) + _PLACEHOLDER_CLOSE)
            i = end
            continue
        out.append(text[i])
        i += 1
    return ''.join(out), protected


def _restore_math_and_currency(html_text, protected):
    """Вернуть математику/валюту на место — экранированными как текст.

    Экранирование (``django.utils.html.escape``) обязательно: без него
    ``$x < y$`` вставил бы в HTML настоящий `<`, и nh3-парсер прочитал бы
    его как начало тега. Экранированный текст переживает HTML-парсинг
    и на экране браузера восстанавливается обратно в `<` — ровно так же,
    как сегодня работает ``plain``-режим через autoescape.
    """
    def repl(match):
        return escape(protected[int(match.group(1))])
    return _PLACEHOLDER_RE.sub(repl, html_text)


# ---------------------------------------------------------------------------
# Markdown — узкое подмножество
# ---------------------------------------------------------------------------

#: `breaks: True` — одиночный перевод строки внутри абзаца становится
#: `<br>` (задача «переносы строк» из CORPUS-FORMAT.md §3), а не мягким
#: пробелом, как в чистом CommonMark. `html: False` — сырой HTML в
#: markdown-источнике экранируется как текст, а не проходит как есть; это
#: первый из двух независимых рубежей защиты, второй — nh3 ниже.
_md = MarkdownIt('zero', {'breaks': True, 'html': False})
_md.enable(['paragraph', 'list', 'table', 'emphasis', 'newline', 'escape'])


# ---------------------------------------------------------------------------
# Санитайзер — второй, независимый рубеж
# ---------------------------------------------------------------------------

#: Строгий allow-list. `p, strong, em, ul, ol, li, br, code, pre` — прямое
#: требование сессии. Таблицы (`table, thead, tbody, tr, th, td`) добавлены
#: поверх буквального списка: без них markdown-таблицы, которых явно
#: требует CORPUS-FORMAT.md §3, рендерились бы голым текстом без структуры.
#: Решение осознанное — таблица без атрибутов не даёт вектора атаки, риск
#: несёт `a`/`img`/`script`/`style`/`iframe`/`on*`, и ни один из них сюда
#: не входит.
_ALLOWED_TAGS = {
    'p', 'strong', 'em', 'ul', 'ol', 'li', 'br', 'code', 'pre',
    'table', 'thead', 'tbody', 'tr', 'th', 'td',
}

#: Теги, которые убираются ЦЕЛИКОМ, вместе с содержимым — не только тег,
#: но и текст внутри. Для остальных тегов вне allow-list nh3 по умолчанию
#: срезает только тег, оставляя текст (`<unknown>hi` → `hi`) — это годится
#: для случайной разметки, но не для `<script>`/`<style>`: там СОДЕРЖИМОЕ
#: само по себе мусор (исходный код), который незачем показывать текстом.
_CLEAN_CONTENT_TAGS = {'script', 'style', 'iframe'}


def _sanitize_html(html_text):
    """Прогнать HTML-фрагмент через nh3 с allow-list. Чистая функция.

    Вынесена отдельно от render_markdown, чтобы тест мог проверить
    allow-list НАПРЯМУЮ, в обход markdown-it — так santiiser доказывает
    свою безопасность сам по себе, а не только «через связку с парсером,
    который и так всё экранирует» (defense in depth).
    """
    return nh3.clean(
        html_text,
        tags=_ALLOWED_TAGS,
        attributes={},  # ноль атрибутов на любом теге, не только on*
        clean_content_tags=_CLEAN_CONTENT_TAGS,
    )


# ---------------------------------------------------------------------------
# Точка входа
# ---------------------------------------------------------------------------

def render_markdown(text):
    """Текст → безопасный HTML-фрагмент. Чистая функция, без побочных эффектов.

    Порядок обязателен и совпадает с описанием в CORPUS-FORMAT.md §2б:
    1. вырезать математику/валюту плейсхолдерами;
    2. остаток — через markdown (узкое подмножество);
    3. вернуть математику/валюту на место, экранированными;
    4. прогнать всё через nh3.

    Пустой текст и ``None`` возвращают пустую строку, не падают —
    в шаблоне это подставляется туда же, куда раньше уходил пустой
    ``plain``-текст.
    """
    if not text:
        return ''
    protected_text, protected = _protect_math_and_currency(text)
    raw_html = _md.render(protected_text)
    restored = _restore_math_and_currency(raw_html, protected)
    return _sanitize_html(restored)
