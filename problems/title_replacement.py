# -*- coding: utf-8 -*-
"""Кого из боевых заголовков заменяет `title_candidate` — правило в одном месте.

**Третья редакция критерия** (решение владельца 07.09.2026 «Критерий замены
заголовков финальный», уточнённое им же на стоп-гейте 08.09). Две предыдущие
ошибались в разные стороны, и обе ошибки измерены:

* первая — «длиннее 40 символов ИЛИ нет термина словаря»: 29 129 замен, снесла
  бы 6 840 хороших длинных заголовков вроде «Закон Оукена при равенстве
  фрикционной и структурной безработицы»;
* вторая — «решает только наличие термина»: 22 289 замен, была применена и
  владельцем откачена. Она ОСТАВЛЯЛА обрубки, если внутри обрубка попадался
  экономический термин: «Потребители в стране покупают товары трех групп:
  товары первой необходимости, но» (id 33070).

**Финальное правило решает не по косвенным признакам, а по обрубочности** —
и проверяется она по самому условию задачи и по метке происхождения, а не по
длине и не по словарю. Три правила, любое срабатывание значит замену.

**Правило 1 — метка происхождения.** `title_source='model-firstline'`:
заголовок вытащен прогоном из первой строки условия, а не придуман автором.
Заменяем безусловно. Те, кого не ловят правила 2 и 3, выглядят так: `'a'`,
`'b'`, `'b, c, d'`, `'50'`, `'2'`, `'КПВ'`, `'Банк'`, `'[рисунок]'` — буквы
вариантов теста и осколки условия, а не клички.

**Правило 2 — обрубок.** Либо заголовок обрывается переносом на чёрточке
(«Активами Центрального банка (ЦБ) явля-») — безусловно, либо он длиннее 40
символов и дословно начинает условие.

⚠️ **Порог 40 стоит у ПРЕФИКСА и только у него, и это не про длину как порок,
а про различение.** Ниже порога префикс перестаёт отличать обрубок от авторской
клички, которую импорт продублировал шапкой условия: «easier than lying»,
«Национальное достояние», «Нам любые дороги дороги», «ШтаКельНо». Замерено:
таких коротких не-firstline заголовков 817 опубликованных, и порог не трогает
ни одного. Цена принята владельцем осознанно: короткий мусор вроде «вопросик»
и «За один бросок 3» остаётся на месте, потому что он неотличим от клички.

⚠️ **У ЧЁРТОЧКИ порога нет** (решение владельца 08.09 на замере). Из 116
коротких не-firstline заголовков, обрывающихся чёрточкой, исключений нет ни
одного: все переносы строки, все опубликованы. Авторской клички, кончающейся
дефисом, не бывает — а с порогом не ловился бы даже пример из карточки решения,
«Активами Центрального банка (ЦБ) явля-» (38 символов).

**Правило 3 — технический номер.** Заголовок начинается со слова «Тест»,
«Задача», «Задание», «Вопрос», «Упражнение», «Пример», «№», `task`, `problem`
и сразу за ним идёт цифра: «Задача 1 ОЧ-2016 (9 класс)», «Тест 23». Это не
авторское название, а его отсутствие.

Не трогаем всё остальное: авторские клички любой бессмысленности («Подсолнух -
2», «It's a life», «Измерение С-37»), осмысленные заголовки ЛЮБОЙ длины
(«Потоварный налог, кривая Лаффера и максимизация сборов» — длина сама по себе
не порок, это прямое решение владельца), задачи с негодным кандидатом и задачи,
где заголовок уже равен кандидату.

⚠️ **Словарь экономических терминов в критерии больше не участвует вовсе.**
Он убран и из кода, и из отчёта — намеренно, чтобы через неделю никто не гадал,
работает эта проверка или нет. Она не работает, потому что её нет.
"""
import re

#: Потолок длины КАНДИДАТА (инвариант §11 прогона) и он же порог правила 2:
#: заголовок обязан быть ДЛИННЕЕ этого, чтобы считаться обрубком.
TITLE_LIMIT = 40

#: Короче этого заголовок совпал бы с началом условия случайно («Монополия» и
#: «Монополия выпускает…»), и это ещё не обрубок. Правило 2 и так требует
#: длиннее 40, но `starts_statement` — функция публичная, и свой минимум ей
#: нужен: без него она отвечала бы «да» на пустую строку.
MIN_ECHO_LEN = 8

#: Имена полей модели, которые баг 07.09 записал вместо значений (882 задачи).
#: Проверяем весь набор, а не одно `'title_candidate'`: если та же ошибка
#: повторится с соседним полем, кандидат «имя поля» не должен пройти молча.
FIELD_NAME_MARKERS = frozenset({
    'title', 'title_candidate', 'title_source', 'enrichment_source',
    'text_quality', 'statement', 'answer', 'solution', 'given', 'find',
    'plot', 'ai_blurb', 'search_queries', 'content_status',
})

#: Кандидат с этими знаками — брак прогона, а не заголовок (инвариант §11).
BAD_CHARS_RE = re.compile(r'[\d$\\]')

#: Всё, что не буква, не цифра и не пробел, — при сверке снимается.
_KEEP_RE = re.compile(r'[^0-9A-Za-zА-Яа-яЁё\s]')

#: Заголовок оборвался переносом строки: «…обязатель-», «Активами ЦБ явля-».
#: Перечислены все ходовые виды чёрточек, включая мягкий перенос U+00AD, —
#: импорт PDF приносит их вперемешку.
_DASH_END_RE = re.compile('[-‐‑‒–—―­]\\s*$')

#: Осколок вёрстки в начале текста: номер задачи, год, баллы. Срезается у
#: ОБЕИХ сторон сверки и только для сверки — см. `compare_key`.
_LEAD_NUMBER_RE = re.compile(r'^[\d\s]+')

#: Технический номер вместо названия. Разделители между словом и цифрой —
#: пробелы, точки, чёрточки и «№»; БУКВ среди них нет намеренно, иначе
#: «Тестирование рынка 5» и «Примерно 5 фирм» попали бы под замену.
_TECH_NUMBER_RE = re.compile(
    '^\\s*(?:тест|задача|задание|вопрос|упражнение|пример|task|problem|№)'
    '[\\s.‐‑‒–—―№-]*\\d',
    re.IGNORECASE)


def normalized(text):
    """Ключ сверки заголовка с условием. В базу НИЧЕГО из этого не пишется.

    Пять шагов подряд, порядок важен: (1) схлопнуть пробелы и обрезать края,
    (2) нижний регистр, (3) «ё» → «е», (4) убрать всё, что не буква, не цифра
    и не пробел, (5) снова обрезать края.

    ⚠️ Шаги 3 и 4 — это и есть починка детектора «эхо условия». Он сравнивал
    тексты буквально и ломался на одной букве: заголовок «…товары трех групп»
    против условия «…товары трёх групп». Замерено на банке: среди `kept` с
    годным кандидатом буквальное сравнение находит 318 совпадений, «ё»→«е» в
    одиночку добавляет 5, снятие пунктуации — 465, вместе получается 828.
    То есть виновата в первую очередь пунктуация, а не «ё».
    """
    строка = re.sub(r'\s+', ' ', (text or '')).strip().lower()
    строка = строка.replace('ё', 'е')
    return _KEEP_RE.sub('', строка).strip()


def candidate_of(problem):
    return (problem.title_candidate or '').strip()


def candidate_is_usable(candidate):
    """Кандидат годен к переносу в боевой заголовок.

    ⚠️ Пробелы снимаются ЗДЕСЬ, а не только в `candidate_of`: иначе кандидат
    из одних пробелов прошёл бы проверку и стёр боевой заголовок в пустоту.
    """
    candidate = (candidate or '').strip()
    if not candidate:
        return False
    if candidate.lower() in FIELD_NAME_MARKERS:
        return False
    if len(candidate) > TITLE_LIMIT:
        return False
    return not BAD_CHARS_RE.search(candidate)


# --- Правило 1: метка происхождения ---------------------------------------- #

def is_first_line_title(problem):
    """Заголовок вытащен прогоном из первой строки условия, а не придуман."""
    return problem.title_source == 'model-firstline'


# --- Правило 2: обрубок длиннее 40 символов -------------------------------- #

def compare_key(text):
    """Ключ сверки: нормализация плюс срезанное ведущее число.

    ⚠️ Срезание — не косметика, а починка ложного отрицания, найденная на
    живом банке. Импорт оставляет в начале текста осколок вёрстки: номер
    задачи, год, баллы. Заголовок его не содержит, и дословное совпадение не
    выходит там, где обрубок очевиден глазами:

        id 6308   заголовок «Конкурентная фирма, максимизирующая»
                  условие   «2009 конкурентная фирма максимизирующая прибыль…»
        id 41249  заголовок «Выберите из списка ниже, все возможные…»
                  условие   «3 выберите из списка ниже все возможные…»

    Обе задачи владелец назвал поимённо как обрубки, и обе оставались бы на
    месте без этого шага.

    ⚠️ Срезаем с ОБЕИХ сторон, а не только у условия (решение владельца 08.09).
    Односторонний вариант ломался ровно там, где номер сохранился и в
    заголовке: «[1] Страны А и Б производят…» против условия «[1] Страны А и
    Б…» — у условия число снято, у заголовка нет, и префикс не сходится.
    """
    return _LEAD_NUMBER_RE.sub('', normalized(text))


def starts_statement(title, statement):
    """Нормализованный заголовок дословно начинает условие."""
    заголовок = compare_key(title)
    условие = compare_key(statement)
    if len(заголовок) < MIN_ECHO_LEN or not условие:
        return False
    return условие.startswith(заголовок)


def ends_with_dash(title):
    """Заголовок обрывается чёрточкой — след переноса строки при импорте."""
    return bool(_DASH_END_RE.search((title or '').rstrip()))


def is_truncation(title, statement):
    """Правило 2: обрыв на чёрточке ЛИБО префикс условия при длине больше 40.

    ⚠️ Порог 40 стоит у ПРЕФИКСА и только у него. Без порога префикс перестаёт
    отличать обрубок от авторской клички, которую импорт продублировал шапкой
    условия («Национальное достояние», «ШтаКельНо»), — 817 опубликованных
    задач.

    ⚠️ У ЧЁРТОЧКИ порога нет, и это решение владельца 08.09 на замере: из 116
    не-firstline заголовков, обрывающихся чёрточкой и коротких, исключений нет
    ни одного — все до одного переносы строки, все опубликованы. Авторской
    клички, кончающейся дефисом, не бывает. Собственный пример владельца
    «Активами Центрального банка (ЦБ) явля-» — 38 символов, то есть под
    порогом он бы не ловился вовсе.
    """
    if ends_with_dash(title):
        return True
    if len((title or '').strip()) <= TITLE_LIMIT:
        return False
    return starts_statement(title, statement)


# --- Правило 3: технический номер ------------------------------------------ #

def is_technical_number(title):
    """«Тест 23», «Задача 1 ОЧ-2016» — номер вместо названия.

    ⚠️ «Задача о двух заводах» цифры не содержит и сюда НЕ попадает: после
    слова обязана идти цифра, между ними допускаются только пробелы, точки,
    чёрточки и «№».
    """
    return bool(_TECH_NUMBER_RE.match(title or ''))


# --- Корзины --------------------------------------------------------------- #

#: Корзины, задачи которых получают новый заголовок. Замена — это ОБЪЕДИНЕНИЕ
#: трёх правил, и от порядка корзин оно не зависит.
REPLACED = ('обрубки', 'технические номера', 'первая строка')

BUCKETS = REPLACED + ('не трогаем', 'уже равен кандидату', 'кандидат негоден')


def bucket(problem):
    """Корзина задачи. Чистая функция: базу не трогает.

    ⚠️ Порядок проверок на СОСТАВ ЗАМЕНЫ не влияет — он влияет только на то,
    в какой корзине задача покажется в отчёте, и выбран ради отчёта:

    * правило 2 («обрубки») раньше правила 3 («номера»), потому что
      обрубочность проверена по самому условию, а номер — по виду заголовка:
      «Задача 5. Фирма производит два товара…» — и то, и другое, и честнее
      считать её обрубком;
    * правило 1 («первая строка») ПОСЛЕДНИМ намеренно. Тогда эта корзина —
      ровно те задачи, которых не поймали правила 2 и 3, то есть самая новая
      и самая непроверенная часть критерия. Владелец просил видеть именно её.
    """
    кандидат = candidate_of(problem)
    if not candidate_is_usable(кандидат):
        return 'кандидат негоден'
    if (problem.title or '').strip() == кандидат:
        return 'уже равен кандидату'
    if is_truncation(problem.title, problem.statement):
        return 'обрубки'
    if is_technical_number(problem.title):
        return 'технические номера'
    if is_first_line_title(problem):
        return 'первая строка'
    return 'не трогаем'
