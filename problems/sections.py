# Обратный указатель «название темы v2 → блок».
_V2_SECTION_BY_NAME = {
    name: V2_SECTION_BY_NUMBER[number]
    for number, name in V2_TOPIC_NAMES.items()
}


def section_of(topic_name):
    """Блок темы по ТОЧНОМУ названию. Незнакомая тема → 'other'.

    Сначала живой канон (23 темы, они сегодня в базе), затем таксономия v2
    (29 тем, они появятся после прогона обогащения). Подстроки и ключевые
    слова не используются намеренно: именно они давали неверные числа на
    радаре статистики.
    """
    name = (topic_name or '').strip()
    if name in CANONICAL_SECTION:
        return CANONICAL_SECTION[name]
    if name in _V2_SECTION_BY_NAME:
        return _V2_SECTION_BY_NAME[name]
    return 'other'


def grouped(topic_names):
    """[(ключ, подпись, [названия тем])] в порядке SECTIONS.

    Пустые блоки не возвращаются: раздел без единой темы — это пустая
    строка на экране, а не сведение о банке задач.
    """
    buckets = {key: [] for key in SECTION_KEYS}
    for name in topic_names:
        buckets[section_of(name)].append(name)
    return [
        (key, label, buckets[key])
        for key, label in SECTIONS
        if buckets[key]
    ]


def canonical_groups():
    """Пять блоков над живыми 23 темами: [(ключ, подпись, [названия])].

    Этим живут фильтры каталога, тренажёра и подборщика домашки. Порядок
    тем внутри блока — тот же, что в `apply_topic_mapping.CANONICAL`
    (вводная → микро → макро → прочее), потому что `CANONICAL_SECTION`
    выше записан в этом порядке.
    """
    return grouped(CANONICAL_SECTION)
